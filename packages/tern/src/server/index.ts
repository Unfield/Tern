import type { Component } from 'svelte';
import { render } from 'svelte/server';
import DefaultError from '../runtime/DefaultError.svelte';
import Passthrough from '../runtime/Passthrough.svelte';
import Root from '../runtime/Root.svelte';
import { setBase } from '../runtime/base.js';
import { revive } from '../runtime/deferred.js';
import { configureI18n, useLocaleSync, type I18nConfig } from '../runtime/i18n.svelte.js';
import { plan } from '../runtime/select.js';
import { applyPayloadToPage } from '../runtime/state.svelte.js';
import type { Payload } from '../runtime/types.js';

/** The server manifest generated by `tern gen` in .tern/generated/server.js. */
export interface ServerManifest {
	layouts: { component: Component<any> | null }[];
	routes: Record<string, { layouts: number[]; page: Component<any>; errors: { layouts: number; component: Component<any> }[] }>;
	fallback: { layouts: number[]; errors: { layouts: number; component: Component<any> }[] };
	i18n?: I18nConfig | null;
	base?: string;
}

/** The result of a server render, as JSON for the Go side. */
export interface RenderResult {
	head?: string;
	body?: string;
	/** True when the payload is not something the server renders. */
	skip?: boolean;
}

/**
 * Creates the function the Go server calls to render a page. It takes the
 * same payload the client receives, so the server and the client render
 * exactly the same tree and hydration matches.
 */
export function createRenderer(manifest: ServerManifest): ((payload: string, href: string) => string) & { raw: (payload: string, href: string) => RenderResult } {
	const layout = (i: number) => manifest.layouts[i]?.component ?? Passthrough;
	configureI18n(manifest.i18n ?? null);
	setBase(manifest.base ?? '');

	// raw returns the result as an object, for a native renderer to read
	// without encoding it as JSON first.
	const raw = (payloadJSON: string, href: string): RenderResult => {
		const p = JSON.parse(payloadJSON) as Payload;
		// Deferred values are still loading: render their pending state.
		if (p.deferred) p.nodes = revive(p.nodes, () => new Promise(() => {}));
		const what = plan(manifest, p);

		let components: Component<any>[];
		switch (what.kind) {
			case 'not-a-page':
				return { skip: true };
			case 'page':
				components = [...what.layouts.map(layout), manifest.routes[what.route]!.page];
				break;
			case 'error': {
				const errors = what.route ? manifest.routes[what.route]!.errors : manifest.fallback.errors;
				components = [...what.layouts.map(layout), errors[what.errorIndex]!.component];
				break;
			}
			case 'default-error':
				components = [DefaultError];
		}

		useLocaleSync(p.locale);
		applyPayloadToPage(p, new URL(href), {}, what.data);
		const form = p.hasForm ? (p.form ?? null) : null;
		const out = render(Root, { props: { components, data: what.data, form } });
		return { head: out.head, body: out.body };
	};
	return Object.assign((payloadJSON: string, href: string) => JSON.stringify(raw(payloadJSON, href)), { raw });
}

