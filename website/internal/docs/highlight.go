package docs

import (
	"bytes"
	"regexp"
	"strings"

	"github.com/alecthomas/chroma/v2"
	"github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/lexers"
	"github.com/alecthomas/chroma/v2/styles"
)

// Highlight returns code as highlighted HTML lines, with the classes
// src/lib/code.css styles.
func Highlight(lang, code string) string {
	l := lexers.Get(lang)
	if l == nil {
		l = lexers.Fallback
	}
	it, err := chroma.Coalesce(l).Tokenise(nil, strings.TrimRight(code, "\n")+"\n")
	if err != nil {
		return code
	}
	var buf bytes.Buffer
	f := html.New(html.WithClasses(true), html.PreventSurroundingPre(true))
	if err := f.Format(&buf, styles.Fallback, it); err != nil {
		return code
	}
	return strings.TrimRight(buf.String(), "\n")
}

var commentRe = regexp.MustCompile(`/\*.*?\*/\s*`)

// CodeCSS is the highlighting CSS: GitHub's colors in the light theme and
// GitHub Dark's in the dark one, keyed on <html data-theme>.
func CodeCSS() (string, error) {
	var b bytes.Buffer
	f := html.New(html.WithClasses(true))
	b.WriteString("/* Generated by go generate ./internal/docs from chroma's github and github-dark styles. */\n")
	for _, t := range []struct{ theme, style string }{{"light", "github"}, {"dark", "github-dark"}} {
		var css bytes.Buffer
		if err := f.WriteCSS(&css, styles.Get(t.style)); err != nil {
			return "", err
		}
		for _, line := range strings.Split(strings.TrimSpace(css.String()), "\n") {
			line = strings.TrimSpace(line)
			// The page sets the background and the line numbers.
			// The page sets the background; lexers mark what they don't
			// know as errors, which isn't the reader's business.
			if line == "" || strings.Contains(line, "/* Background */") || strings.Contains(line, "/* PreWrapper */") || strings.Contains(line, "/* Error */") {
				continue
			}
			line = commentRe.ReplaceAllString(line, "")
			b.WriteString(`:root[data-theme="` + t.theme + `"] ` + line + "\n")
		}
	}
	return b.String(), nil
}
