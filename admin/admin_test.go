type link struct {
	ID      int64      `admin:"key"`
	Title   string     `validate:"required,max=50" admin:"list,search"`
	URL     string     `validate:"required,url" label:"Address" admin:"list,search"`
	Kind    string     `validate:"oneof=article|video" admin:"list,filter"`
	Read    bool       `admin:"list,filter"`
	Notes   *string    `admin:"textarea" description:"Only you see these."`
	UserID  int64      `label:"Owner" admin:"list,ref=users"`
	AddedAt time.Time  `admin:"list,readonly"`
	ReadAt  *time.Time `admin:"date"`
}

func (l *link) Validate() error {
	if strings.Contains(l.Title, "spam") {
		return kit.FieldError("title", "No spam.")
	}
	return nil
}

type user struct {
	ID       int64  `admin:"key"`
	Email    string `validate:"required,email"`
	JoinedAt int64  `admin:"unixms"`
	SeenAt   *int64 `admin:"unix,date"`
}

const schema = `CREATE TABLE links (
	id INTEGER PRIMARY KEY %s,
	title TEXT NOT NULL,
	url TEXT NOT NULL,
	kind TEXT NOT NULL DEFAULT '',
	read BOOLEAN NOT NULL DEFAULT FALSE,
	notes TEXT,
	user_id INTEGER NOT NULL DEFAULT 0,
	added_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	read_at TIMESTAMP
)`

type data struct {
	View      string `json:"view"`
	Counts    []int  `json:"counts"`
	Notice    string `json:"notice"`
	Resources []struct {
		Name, Href string
	} `json:"resources"`
	Resource struct {
		Key    string `json:"key"`
		Fields []struct {
			Name     string   `json:"name"`
			Input    string   `json:"input"`
			Options  []string `json:"options"`
			ReadOnly bool     `json:"readonly"`
			List     bool     `json:"list"`
			Ref      string   `json:"ref"`
		} `json:"fields"`
		Search bool `json:"search"`
	} `json:"resource"`
	List struct {
		Rows []struct {
			Key    string            `json:"key"`
			Values map[string]string `json:"values"`
		} `json:"rows"`
		Total int `json:"total"`
		Pages int `json:"pages"`
	} `json:"list"`
	Record struct {
		Key    string            `json:"key"`
		Values map[string]string `json:"values"`
	} `json:"record"`
}

type result struct {
	Type     string            `json:"type"`
	Status   int               `json:"status"`
	Location string            `json:"location"`
	Nodes    []json.RawMessage `json:"nodes"`
	Data     struct {
		Errors  map[string]string `json:"errors"`
		Values  map[string]any    `json:"values"`
		Message string            `json:"message"`
	} `json:"data"`
}

// hooks records AfterSave and AfterDelete calls.
var hooks []string

func setup(t *testing.T, db *sql.DB, allow *bool) http.Handler {
	hooks = nil
	t.Helper()
	ctx := context.Background()
	auto := ""
	if d, _ := sqldb.Detect(db); d == sqldb.Postgres {
		auto = "GENERATED BY DEFAULT AS IDENTITY"
	}
	for _, q := range []string{strings.Replace(schema, "%s", auto, 1), `CREATE TABLE users (id INTEGER PRIMARY KEY ` + auto + `, email TEXT NOT NULL UNIQUE, joined_at BIGINT NOT NULL DEFAULT 0, seen_at BIGINT)`} {
		if _, err := db.ExecContext(ctx, q); err != nil {
			t.Fatal(err)
		}
	}
	links, err := admin.NewTable[link](db, "links", "")
	if err != nil {
		t.Fatal(err)
	}
	users, err := admin.NewTable[user](db, "users", "")
	if err != nil {
		t.Fatal(err)
	}
	panel := admin.New(admin.Options{PerPage: 2, Authorize: func(c *kit.Ctx) error {
		if !*allow {
			return kit.Error(http.StatusForbidden, "")
		}
		return nil
	}}, admin.Resource("links", links,
		admin.AfterSave(func(_ context.Context, key string) error { hooks = append(hooks, "saved "+key); return nil }),
		admin.AfterDelete(func(_ context.Context, key string) error { hooks = append(hooks, "deleted "+key); return nil }),
	), admin.Resource("users", users, admin.NoDelete()))
	app, err := kit.New(&kit.Manifest{AppHTML: `<html><head>%tern.head%</head><body>%tern.body%</body></html>`, Routes: []kit.RouteDef{
		{ID: "/admin/path.rest", Page: &kit.PageDef{Component: "src/routes/admin/+page.svelte", Load: kit.LoadOf(admin.Load), Actions: admin.Actions}},
	}}, kit.WithLogger(slog.New(slog.NewTextHandler(io.Discard, nil))), kit.WithPlugins(panel))
	if err != nil {
		t.Fatal(err)
	}
	return app
}

func get(t *testing.T, h http.Handler, path string) (result, data) {
	t.Helper()
	u, _ := url.Parse(path)
	u.Path = strings.TrimSuffix(u.Path, "/") + "/__data.json"
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, u.String(), nil))
	var r result
	if err := json.Unmarshal(rec.Body.Bytes(), &r); err != nil {
		t.Fatalf("%s: %v: %s", path, err, rec.Body)
	}
	var d data
	if len(r.Nodes) > 0 {
		if err := json.Unmarshal(r.Nodes[len(r.Nodes)-1], &d); err != nil {
			t.Fatalf("%s: %v", path, err)
		}
	}
	return r, d
}

func post(t *testing.T, h http.Handler, path string, form url.Values) result {
	t.Helper()
	req := httptest.NewRequest(http.MethodPost, path, strings.NewReader(form.Encode()))
	req.Header.Set("Content-Type", "application/x-www-form-urlencoded")
	req.Header.Set("X-Tern-Action", "true")
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, req)
	var r result
	if err := json.Unmarshal(rec.Body.Bytes(), &r); err != nil {
		t.Fatalf("%s: %v: %s", path, err, rec.Body)
	}
	return r
}

func TestAdmin(t *testing.T) {
	dbtest.Each(t, func(t *testing.T, db *sql.DB) {
		allow := true
		app := setup(t, db, &allow)

		// Creating checks the struct's rules, then its Validate method.
		bad := post(t, app, "/admin/links/new?/save", url.Values{"title": {""}, "url": {"nope"}, "kind": {"podcast"}})
		if bad.Type != "failure" || bad.Status != 400 || bad.Data.Errors["title"] == "" || bad.Data.Errors["url"] == "" || bad.Data.Errors["kind"] == "" {
			t.Fatalf("bad create = %+v", bad)
		}
		if bad.Data.Values["url"] != "nope" {
			t.Errorf("values aren't sent back: %v", bad.Data.Values)
		}
		spam := post(t, app, "/admin/links/new?/save", url.Values{"title": {"spam"}, "url": {"https://a.example"}, "kind": {"video"}})
		if spam.Data.Errors["title"] != "No spam." {
			t.Errorf("Validate isn't run: %+v", spam)
		}
		for i, title := range []string{"Go blog", "Svelte docs", "Rust book"} {
			form := url.Values{"title": {title}, "url": {"https://" + strings.ReplaceAll(strings.ToLower(title), " ", "") + ".example"}, "kind": {"article"}, "user_id": {"1"}}
			if i == 1 {
				form.Set("read", "on")
				form.Set("read_at", "2026-11-01")
			}
			if r := post(t, app, "/admin/links/new?/save", form); r.Type != "redirect" || r.Location != "/admin/links?done=created" {
				t.Fatalf("create = %+v", r)
			}
		}

		// The home screen counts each resource's records.
		if _, d := get(t, app, "/admin"); d.View != "home" || len(d.Counts) != 2 || d.Counts[0] != 3 || d.Counts[1] != 0 {
			t.Errorf("home = %+v", d)
		}

		// Lists page, search, filter and sort.
		_, d := get(t, app, "/admin/links")
		if d.View != "list" || d.List.Total != 3 || d.List.Pages != 2 || len(d.List.Rows) != 2 || d.List.Rows[0].Values["title"] != "Rust book" {
			t.Fatalf("list = %+v", d.List)
		}
		if _, ok := d.List.Rows[0].Values["notes"]; ok {
			t.Error("unlisted fields are in the list")
		}
		if d.Resource.Key != "id" || !d.Resource.Search {
			t.Errorf("resource = %+v", d.Resource)
		}
		for _, f := range d.Resource.Fields {
			switch f.Name {
			case "kind":
				if f.Input != "select" || len(f.Options) != 2 {
					t.Errorf("kind = %+v", f)
				}
			case "notes":
				if f.Input != "textarea" || f.List {
					t.Errorf("notes = %+v", f)
				}
			case "added_at":
				if f.Input != "datetime-local" || !f.ReadOnly {
					t.Errorf("added_at = %+v", f)
				}
			case "read_at":
				if f.Input != "date" {
					t.Errorf("read_at = %+v", f)
				}
			case "user_id":
				if f.Ref != "users" {
					t.Errorf("user_id = %+v", f)
				}
			}
		}
		if _, d := get(t, app, "/admin/links?page=2"); len(d.List.Rows) != 1 || d.List.Rows[0].Values["title"] != "Go blog" {
			t.Errorf("page 2 = %+v", d.List.Rows)
		}
		if _, d := get(t, app, "/admin/links?q=SVELTE"); d.List.Total != 1 || d.List.Rows[0].Values["read"] != "true" {
			t.Errorf("search = %+v", d.List)
		}
		if _, d := get(t, app, "/admin/links?q=100%25"); d.List.Total != 0 {
			t.Errorf("%% is matched literally: %+v", d.List)
		}
		if _, d := get(t, app, "/admin/links?read=false"); d.List.Total != 2 {
			t.Errorf("filter = %+v", d.List)
		}
		if _, d := get(t, app, "/admin/links?sort=title"); d.List.Rows[0].Values["title"] != "Go blog" || d.List.Rows[1].Values["title"] != "Rust book" {
			t.Errorf("sort = %+v", d.List.Rows)
		}
		if r, _ := get(t, app, "/admin/links?sort=-nope"); r.Type != "data" {
			t.Errorf("an unknown sort is ignored: %+v", r)
		}

		// The form has the record's values; read-only fields stay as they were.
		_, d = get(t, app, "/admin/links?q=svelte")
		key := d.List.Rows[0].Key
		_, d = get(t, app, "/admin/links/"+key)
		if d.View != "form" || d.Record.Key != key || d.Record.Values["read_at"] != "2026-11-01" || d.Record.Values["added_at"] == "" {
			t.Fatalf("form = %+v", d.Record)
		}
		added := d.Record.Values["added_at"]
		edit := url.Values{"title": {"Svelte tutorial"}, "url": {"https://svelte.example"}, "kind": {"video"}, "notes": {"later"}, "user_id": {"1"}, "added_at": {"2000-01-01T00:00"}}
		if r := post(t, app, "/admin/links/"+key+"?/save", edit); r.Type != "redirect" || r.Location != "/admin/links?done=saved" {
			t.Fatalf("save = %+v", r)
		}
		_, d = get(t, app, "/admin/links/"+key)
		v := d.Record.Values
		if v["title"] != "Svelte tutorial" || v["kind"] != "video" || v["read"] != "" || v["notes"] != "later" || v["read_at"] != "" || v["added_at"] != added {
			t.Errorf("after save = %+v", v)
		}

		// A database error, such as a unique column, fails the form.
		// Integers can hold times.
		post(t, app, "/admin/users/new?/save", url.Values{"email": {"a@example.com"}, "joined_at": {"2026-11-12T08:30"}, "seen_at": {"2026-11-13"}})
		var joined, seen int64
		if err := db.QueryRow(`SELECT joined_at, seen_at FROM users`).Scan(&joined, &seen); err != nil || joined != time.Date(2026, 11, 12, 8, 30, 0, 0, time.UTC).UnixMilli() || seen != time.Date(2026, 11, 13, 0, 0, 0, 0, time.UTC).Unix() {
			t.Errorf("times = %d, %d, %v", joined, seen, err)
		}
		if _, d := get(t, app, "/admin/users/1"); d.Record.Values["joined_at"] != "2026-11-12T08:30" || d.Record.Values["seen_at"] != "2026-11-13" {
			t.Errorf("user = %+v", d.Record.Values)
		}
		if r := post(t, app, "/admin/users/new?/save", url.Values{"email": {"a@example.com"}}); r.Type != "failure" || r.Data.Message == "" {
			t.Errorf("duplicate = %+v", r)
		}

		// Deleting, where it's allowed.
		if r := post(t, app, "/admin/users/1?/delete", nil); r.Status != http.StatusMethodNotAllowed {
			t.Errorf("NoDelete = %+v", r)
		}
		if r := post(t, app, "/admin/links/"+key+"?/delete", nil); r.Location != "/admin/links?done=deleted" {
			t.Errorf("delete = %+v", r)
		}
		if got := strings.Join(hooks, ","); got != "saved 1,saved 2,saved 3,saved "+key+",deleted "+key {
			t.Errorf("hooks = %s", got)
		}
		for _, p := range []string{"/admin/links/" + key, "/admin/nope", "/admin/links/abc", "/admin/links/1/2"} {
			if r, _ := get(t, app, p); r.Status != http.StatusNotFound {
				t.Errorf("%s = %+v", p, r)
			}
		}
		if r := post(t, app, "/admin/links/"+key+"?/save", edit); r.Status != http.StatusNotFound {
			t.Errorf("saving a deleted record = %+v", r)
		}

		// Authorize guards screens and actions.
		allow = false
		if r, _ := get(t, app, "/admin"); r.Status != http.StatusForbidden {
			t.Errorf("screen = %+v", r)
		}
		if r := post(t, app, "/admin/links/new?/save", edit); r.Status != http.StatusForbidden {
			t.Errorf("action = %+v", r)
		}
	})
}

func TestBadPanels(t *testing.T) {
	type nokey struct{ Name string }
	type badtag struct {
		ID int64 `admin:"sparkly"`
	}
	type badtype struct {
		ID   int64
		Tags []string
	}
	db, _ := sql.Open("sqlite", ":memory:")
	defer func() { _ = db.Close() }()
	for name, fn := range map[string]func() error{
		"no key":   func() error { _, err := admin.NewTable[nokey](db, "x", ""); return err },
		"bad tag":  func() error { _, err := admin.NewTable[badtag](db, "x", ""); return err },
		"bad type": func() error { _, err := admin.NewTable[badtype](db, "x", ""); return err },
	} {
		if fn() == nil {
			t.Errorf("%s: no error", name)
		}
	}
	links, _ := admin.NewTable[link](db, "links", "")
	for name, p := range map[string]*admin.Admin{
		"no authorize": admin.New(admin.Options{}, admin.Resource("users", links)),
		"missing ref":  admin.New(admin.Options{Authorize: func(*kit.Ctx) error { return nil }}, admin.Resource("links", links)),
		"same name":    admin.New(admin.Options{Authorize: func(*kit.Ctx) error { return nil }}, admin.Resource("links", links), admin.Resource("links", links)),
	} {
		if _, err := kit.New(&kit.Manifest{AppHTML: `<html><head>%tern.head%</head><body>%tern.body%</body></html>`}, kit.WithPlugins(p)); err == nil {
			t.Errorf("%s: no error", name)
		}
	}
}
