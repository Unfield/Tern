package codegen

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/Unfield/Tern/internal/i18n"
)

// LocalesDir holds the app's messages, one <locale>.json per language.
const LocalesDir = "src/locales"

// loadLocales validates src/locales, if the app has it.
func (g *generator) loadLocales() error {
	dir := filepath.Join(g.root, filepath.FromSlash(LocalesDir))
	if _, err := os.Stat(dir); err != nil {
		return nil //nolint:nilerr // no locales: i18n is off
	}
	cat, err := i18n.Load(os.DirFS(dir), g.cfg.I18n.DefaultLocale)
	if err != nil {
		return fmt.Errorf("%s: %w", LocalesDir, err)
	}
	g.locales = cat
	for locale, keys := range cat.Missing() {
		shown := keys
		if len(shown) > 5 {
			shown = append(shown[:5:5], fmt.Sprintf("and %d more", len(keys)-5))
		}
		g.warnings = append(g.warnings, fmt.Sprintf("%s/%s.json is missing %s; the %s text is used", LocalesDir, locale, strings.Join(shown, ", "), cat.Default))
	}
	return nil
}

// i18nClient returns the client manifest's i18n export.
func (g *generator) i18nClient() string {
	if g.locales == nil {
		return "export const i18n = null;\n"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "export const i18n = {\n\tdefaultLocale: %q,\n\tlocales: %s,\n\tload: {\n", g.locales.Default, jsStrings(g.locales.Locales))
	for _, l := range g.locales.Locales {
		fmt.Fprintf(&b, "\t\t%q: () => import(%q),\n", l, "../../"+LocalesDir+"/"+l+".json")
	}
	b.WriteString("\t}\n};\n")
	return b.String()
}

// i18nServer returns the imports and config for the server renderer.
func (g *generator) i18nServer() (imports, config string) {
	if g.locales == nil {
		return "", "null"
	}
	var imp, cfg strings.Builder
	fmt.Fprintf(&cfg, "{ defaultLocale: %q, messages: { ", g.locales.Default)
	for i, l := range g.locales.Locales {
		fmt.Fprintf(&imp, "import L%d from %q;\n", i, "../../"+LocalesDir+"/"+l+".json")
		fmt.Fprintf(&cfg, "%q: L%d, ", l, i)
	}
	cfg.WriteString("} }")
	return imp.String(), cfg.String()
}

// i18nTypes declares the message keys, so t() is type-checked.
func (g *generator) i18nTypes() {
	var b strings.Builder
	b.WriteString("// Code generated by tern; DO NOT EDIT.\n\nimport '@ternkit/tern';\n\ndeclare module '@ternkit/tern' {\n\t/** The message keys in src/locales. */\n\tinterface Messages {\n")
	if g.locales != nil {
		for _, k := range g.locales.Keys() {
			fmt.Fprintf(&b, "\t\t%q: true;\n", k)
		}
	}
	b.WriteString("\t}\n}\n")
	g.files[".tern/generated/i18n.d.ts"] = []byte(b.String())
}

func jsStrings(v []string) string {
	q := make([]string, len(v))
	for i, s := range v {
		q[i] = fmt.Sprintf("%q", s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}
