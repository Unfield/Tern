package codegen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/Unfield/Tern/internal/routes"
)

// linkPatterns returns the pattern each route is linked by in $routes,
// such as "/projects/[id]". Matchers are left out unless two routes would
// otherwise share a pattern.
func linkPatterns(m *routes.Manifest) map[string]*routes.Route {
	plain := func(r *routes.Route, matchers bool) string {
		if len(r.Segments) == 0 {
			return "/"
		}
		var b strings.Builder
		for _, s := range r.Segments {
			b.WriteByte('/')
			if matchers {
				b.WriteString(s.Pattern())
				continue
			}
			switch s.Kind {
			case routes.Param:
				b.WriteString("[" + s.Value + "]")
			case routes.OptionalParam:
				b.WriteString("[[" + s.Value + "]]")
			case routes.Rest:
				b.WriteString("[..." + s.Value + "]")
			default:
				b.WriteString(s.Value)
			}
		}
		return b.String()
	}
	count := map[string]int{}
	for _, r := range m.Routes {
		count[plain(r, false)]++
	}
	out := map[string]*routes.Route{}
	for _, r := range m.Routes {
		key := plain(r, false)
		if count[key] > 1 {
			key = plain(r, true)
		}
		out[key] = r
	}
	return out
}

const routesJS = `// Code generated by tern; DO NOT EDIT.

const patterns = new Set(%s);

/**
 * Builds the URL path of a route from its pattern and parameters:
 * route('/projects/[id]', { id: 42 }) is '/projects/42'.
 */
export function route(pattern, params = {}) {
	if (import.meta.env?.DEV && !patterns.has(pattern)) {
		console.warn(` + "`" + `[tern] route(): unknown route pattern ${pattern}` + "`" + `);
	}
	let path = '';
	for (const segment of pattern.split('/')) {
		if (!segment) continue;
		let m;
		if ((m = /^\[\[(\w+)(?:=\w+)?\]\]$/.exec(segment))) {
			const v = params[m[1]];
			if (v !== undefined && v !== null && v !== '') path += '/' + encodeURIComponent(String(v));
		} else if ((m = /^\[\.\.\.(\w+)(?:=\w+)?\]$/.exec(segment))) {
			const v = params[m[1]];
			const parts = Array.isArray(v) ? v : String(v ?? '').split('/');
			for (const p of parts) if (p !== '') path += '/' + encodeURIComponent(String(p));
		} else if ((m = /^\[(\w+)(?:=\w+)?\]$/.exec(segment))) {
			const v = params[m[1]];
			if (v === undefined || v === null || v === '') throw new Error(` + "`" + `route(): missing parameter "${m[1]}" for ${pattern}` + "`" + `);
			path += '/' + encodeURIComponent(String(v));
		} else {
			path += '/' + segment;
		}
	}
	return path || '/';
}
`

const routesDTS = `// Code generated by tern; DO NOT EDIT.

/** Every route in the app, with the parameters its URL needs. */
export interface Routes {
%s}

/** A route pattern, such as '/projects/[id]'. */
export type RoutePattern = keyof Routes;

type Args<P extends RoutePattern> = [keyof Routes[P]] extends [never]
	? [params?: Record<string, never>]
	: {} extends Routes[P]
		? [params?: Routes[P]]
		: [params: Routes[P]];

/**
 * Builds the URL path of a route from its pattern and parameters:
 * route('/projects/[id]', { id: 42 }) is '/projects/42'. TypeScript checks
 * that the pattern exists and that required parameters are given.
 */
export function route<P extends RoutePattern>(pattern: P, ...params: Args<P>): string;
`

func (g *generator) linksModule() {
	links := linkPatterns(g.m)
	keys := make([]string, 0, len(links))
	for k := range links {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var dts strings.Builder
	for _, k := range keys {
		var fields []string
		for _, p := range links[k].Params() {
			switch p.Kind {
			case routes.OptionalParam:
				fields = append(fields, fmt.Sprintf("%s?: string | number", tsKey(p.Value)))
			case routes.Rest:
				fields = append(fields, fmt.Sprintf("%s?: string | string[]", tsKey(p.Value)))
			default:
				fields = append(fields, fmt.Sprintf("%s: string | number", tsKey(p.Value)))
			}
		}
		typ := "Record<string, never>"
		if len(fields) > 0 {
			typ = "{ " + strings.Join(fields, "; ") + " }"
		}
		fmt.Fprintf(&dts, "\t%q: %s;\n", k, typ)
	}
	quoted := make([]string, len(keys))
	for i, k := range keys {
		quoted[i] = fmt.Sprintf("%q", k)
	}
	g.files[".tern/generated/routes.js"] = []byte(fmt.Sprintf(routesJS, "["+strings.Join(quoted, ", ")+"]"))
	g.files[".tern/generated/routes.d.ts"] = []byte(fmt.Sprintf(routesDTS, dts.String()))
}
