package codegen

import (
	"fmt"
	"go/ast"
	"go/constant"
	"go/types"
	"path/filepath"
	"strings"

	"golang.org/x/tools/go/packages"
)

const goscriptPath = "github.com/Unfield/Tern/goscript"

// LiveTypesDir holds the TypeScript types of live components' state and
// Funcs, which tern check uses to type-check their markup.
const LiveTypesDir = GenDir + "/goscript/types"

// liveShape is what a live component's markup can use.
type liveShape struct {
	state map[string]string // name → TS type
	funcs map[string]string // name → TS LiveFunc type
	decls []string          // named types they use
}

// liveTypes type-checks the generated live packages and writes a TS module
// per component. A component that doesn't compile gets loose types; the Go
// build reports its errors.
func (g *generator) liveTypes(comps []liveComponent, imports map[string]string) {
	overlay := map[string][]byte{}
	var patterns []string
	byPath := map[string]string{}
	for _, c := range comps {
		name := LiveDir + "/" + c.id + "/component.go"
		overlay[filepath.Join(g.root, filepath.FromSlash(name))] = g.files[name]
		patterns = append(patterns, imports[c.id])
		byPath[imports[c.id]] = c.id
	}
	cfg := &packages.Config{
		Mode:    packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo,
		Dir:     g.root,
		Overlay: overlay,
	}
	pkgs, err := packages.Load(cfg, patterns...)
	shapes := map[string]*liveShape{}
	if err == nil {
		for _, p := range pkgs {
			if id, ok := byPath[p.PkgPath]; ok && p.TypesInfo != nil {
				shapes[id] = shapeOf(p)
			}
		}
	}
	for _, c := range comps {
		var b strings.Builder
		b.WriteString("// Code generated by tern from <script lang=\"go\" live>; DO NOT EDIT.\n\nimport type { LiveFunc } from '@ternkit/tern/goscript';\n\n")
		s := shapes[c.id]
		var state, funcs []string
		if s != nil {
			for _, n := range sortedKeys(s.state) {
				state = append(state, fmt.Sprintf("\t%s: %s;", tsKey(n), s.state[n]))
			}
			for _, n := range sortedKeys(s.funcs) {
				funcs = append(funcs, fmt.Sprintf("\t%s: %s;", tsKey(n), s.funcs[n]))
			}
		}
		body := func(lines []string, loose string) string {
			if s == nil {
				return loose
			}
			if len(lines) == 0 {
				return "{}"
			}
			return "{\n" + strings.Join(lines, "\n") + "\n}"
		}
		if s != nil && len(s.decls) > 0 {
			b.WriteString(strings.Join(s.decls, "\n\n"))
			b.WriteString("\n\n")
		}
		fmt.Fprintf(&b, "export type State = %s;\n\nexport type Funcs = %s;\n", body(state, "Record<string, any>"), body(funcs, "Record<string, LiveFunc<any[], any>>"))
		g.files[LiveTypesDir+"/"+c.id+".ts"] = []byte(b.String())
	}
}

// shapeOf finds the State, Derived, Show and Func calls in a package.
func shapeOf(p *packages.Package) *liveShape {
	s := &liveShape{state: map[string]string{}, funcs: map[string]string{}}
	e := newTSEmitter()
	info := p.TypesInfo
	for _, f := range p.Syntax {
		ast.Inspect(f, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			fn := calledFunc(info, call)
			if fn == nil || fn.Pkg() == nil || fn.Pkg().Path() != goscriptPath {
				return true
			}
			sig, _ := fn.Type().(*types.Signature)
			recv := ""
			if sig != nil && sig.Recv() != nil {
				recv = recvName(sig.Recv().Type())
			}
			switch {
			case recv == "" && (fn.Name() == "State" || fn.Name() == "Derived"):
				if name := stringArg(info, call, 1); name != "" {
					s.state[name] = e.typeOf(signalElem(info.TypeOf(call)))
				}
			case fn.Name() == "Show" && (recv == "GlobalSignal" || recv == "SharedSignal" || recv == "PresenceCounter"):
				if name := stringArg(info, call, 1); name != "" {
					s.state[name] = e.typeOf(signalElem(info.TypeOf(call)))
				}
			case fn.Name() == "Func" && recv == "Component":
				if name := stringArg(info, call, 0); name != "" && len(call.Args) > 1 {
					if fs, ok := info.TypeOf(call.Args[1]).Underlying().(*types.Signature); ok {
						s.funcs[name] = funcType(e, fs)
					}
				}
			}
			return true
		})
	}
	s.decls = e.decls
	return s
}

func calledFunc(info *types.Info, call *ast.CallExpr) *types.Func {
	fun := call.Fun
	if ix, ok := fun.(*ast.IndexExpr); ok { // State[int](...)
		fun = ix.X
	}
	if ix, ok := fun.(*ast.IndexListExpr); ok {
		fun = ix.X
	}
	var id *ast.Ident
	switch f := fun.(type) {
	case *ast.Ident:
		id = f
	case *ast.SelectorExpr:
		id = f.Sel
	default:
		return nil
	}
	fn, _ := info.Uses[id].(*types.Func)
	if fn != nil {
		return fn.Origin()
	}
	return nil
}

func recvName(t types.Type) string {
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	if n, ok := types.Unalias(t).(*types.Named); ok {
		return n.Obj().Name()
	}
	return ""
}

func stringArg(info *types.Info, call *ast.CallExpr, i int) string {
	if i >= len(call.Args) {
		return ""
	}
	tv, ok := info.Types[call.Args[i]]
	if !ok || tv.Value == nil || tv.Value.Kind() != constant.String {
		return ""
	}
	return constant.StringVal(tv.Value)
}

// signalElem returns T for *goscript.Signal[T].
func signalElem(t types.Type) types.Type {
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	if n, ok := types.Unalias(t).(*types.Named); ok && n.TypeArgs().Len() == 1 {
		return n.TypeArgs().At(0)
	}
	return types.Typ[types.Invalid]
}

// funcType is the LiveFunc type for a Func: its arguments without a
// leading context, and its value result.
func funcType(e *tsEmitter, fs *types.Signature) string {
	var params []string
	for i := range fs.Params().Len() {
		v := fs.Params().At(i)
		t := v.Type()
		if i == 0 && isContext(t) {
			continue
		}
		name := v.Name()
		if name == "" || name == "_" {
			name = fmt.Sprintf("arg%d", len(params)+1)
		}
		ts := e.typeOf(t)
		if isGoscriptEvent(t) {
			ts = "Event | { value?: string; checked?: boolean; key?: string }"
		}
		params = append(params, name+": "+ts)
	}
	result := "void"
	for i := range fs.Results().Len() {
		t := fs.Results().At(i).Type()
		if types.Identical(t, types.Universe.Lookup("error").Type()) {
			continue
		}
		result = e.typeOf(t)
	}
	return fmt.Sprintf("LiveFunc<[%s], %s>", strings.Join(params, ", "), result)
}

func isContext(t types.Type) bool {
	n, ok := types.Unalias(t).(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == "context" && n.Obj().Name() == "Context"
}

func isGoscriptEvent(t types.Type) bool {
	n, ok := types.Unalias(t).(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == goscriptPath && n.Obj().Name() == "Event"
}
