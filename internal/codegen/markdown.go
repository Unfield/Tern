package codegen

import (
	"encoding/json"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"strings"

	"github.com/Unfield/Tern/internal/markdown"
	"github.com/Unfield/Tern/internal/routes"
)

// MarkdownPagesDir holds the Svelte components generated from +page.md files.
const MarkdownPagesDir = ".tern/generated/pages"

// ContentDir holds Markdown collections read with the content package.
const ContentDir = "src/content"

// markdownPages renders every +page.md into a Svelte component. The
// front matter's title and description go into <svelte:head>, and all of it
// is exported as metadata from the component's module script.
func (g *generator) markdownPages() error {
	for _, r := range g.m.Routes {
		if path.Base(r.Page) != routes.FilePageMarkdown {
			continue
		}
		src, err := os.ReadFile(filepath.Join(g.root, filepath.FromSlash(path.Join(RoutesDir, r.Page))))
		if err != nil {
			return err
		}
		front := map[string]any{}
		doc, err := markdown.Parse(src, &front)
		if err != nil {
			return fmt.Errorf("%s: %w", path.Join(RoutesDir, r.Page), err)
		}
		g.files[routeFile(r.Page)] = []byte(markdownComponent(front, doc))
	}
	return nil
}

func markdownComponent(front map[string]any, doc markdown.Document) string {
	meta, err := json.Marshal(front)
	if err != nil {
		meta = []byte("{}")
	}
	html, _ := json.Marshal(doc.HTML)
	headings, _ := json.Marshal(doc.Headings)
	var b strings.Builder
	b.WriteString("<!-- Code generated by tern from a +page.md file; DO NOT EDIT. -->\n")
	b.WriteString("<script module>\n")
	fmt.Fprintf(&b, "\texport const metadata = %s;\n", meta)
	fmt.Fprintf(&b, "\texport const headings = %s;\n", headings)
	fmt.Fprintf(&b, "\tconst html = %s;\n", html)
	b.WriteString("</script>\n\n")
	_, hasTitle := front["title"].(string)
	_, hasDesc := front["description"].(string)
	if hasTitle || hasDesc {
		b.WriteString("<svelte:head>\n")
		if hasTitle {
			b.WriteString("\t<title>{metadata.title}</title>\n")
		}
		if hasDesc {
			b.WriteString("\t<meta name=\"description\" content={metadata.description} />\n")
		}
		b.WriteString("</svelte:head>\n\n")
	}
	b.WriteString("<div class=\"markdown\">{@html html}</div>\n")
	return b.String()
}

// hasContent reports whether the app has a src/content directory to embed.
func (g *generator) hasContent() bool {
	info, err := os.Stat(filepath.Join(g.root, filepath.FromSlash(ContentDir)))
	return err == nil && info.IsDir()
}
