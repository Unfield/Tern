// Dir is where an app keeps its queries, and File the Go file generated
// next to them.
const (
	Dir  = "queries"
	File = "queries.gen.go"
)

// Generate types the queries in root/queries against the schema of the
// app's migrations and returns the Go file for them, or nil when the app
// has no queries.
func Generate(ctx context.Context, root string) ([]byte, error) {
	dir := filepath.Join(root, Dir)
	if info, err := os.Stat(dir); err != nil || !info.IsDir() {
		return nil, nil
	}
	qs, err := parseDir(dir)
	if err != nil {
		return nil, err
	}
	if len(qs) == 0 {
		return nil, nil
	}
	for _, q := range qs {
		q.file = relTo(root, q.file)
	}
	s, err := openScratch(ctx, root)
	if err != nil {
		return nil, err
	}
	defer s.close()
	var errs []string
	for _, q := range qs {
		if q.unchecked {
			for _, p := range q.params {
				p.goType = q.paramTypes[p.name]
			}
			if err := s.typeColumns(ctx, q); err != nil {
				errs = append(errs, err.Error())
			}
			continue
		}
		if e := s.inferParams(q); len(e) > 0 {
			errs = append(errs, e...)
			continue
		}
		if err := s.typeColumns(ctx, q); err != nil {
			errs = append(errs, err.Error())
		}
	}
	if len(errs) == 0 {
		errs = checkRows(qs)
	}
	if len(errs) > 0 {
		return nil, fmt.Errorf("%s", strings.Join(errs, "\n"))
	}
	return render(qs)
}

func relTo(root, file string) string {
	if r, err := filepath.Rel(root, filepath.FromSlash(file)); err == nil {
		return filepath.ToSlash(r)
	}
	return file
}

// checkRows makes sure queries that share a row type (-- row Name) return
// the same columns.
func checkRows(qs []*query) []string {
	var errs []string
	first := map[string]*query{}
	for _, q := range qs {
		if q.row == "" || len(q.columns) < 2 {
			continue
		}
		f, ok := first[q.row]
		if !ok {
			first[q.row] = q
			continue
		}
		if !slices.Equal(f.columns, q.columns) {
			errs = append(errs, fmt.Sprintf("%s:%d: %s returns other columns than %s, which also uses the row type %s", q.file, q.line, q.name, f.name, q.row))
		}
	}
	return errs
}

func render(qs []*query) ([]byte, error) {
	var b bytes.Buffer
	imports := map[string]bool{"context": true, "database/sql": true, "errors": true, "github.com/Unfield/Tern/sqldb": true}
	for _, q := range qs {
		for _, p := range q.params {
			addImport(imports, p.goType)
		}
		for _, c := range q.columns {
			addImport(imports, c.goType)
		}
	}
	b.WriteString("// Code generated by tern from queries/*.sql; DO NOT EDIT.\n\n")
	b.WriteString("// Package queries runs the app's SQL queries, typed from its schema (see\n// docs/sql.md).\npackage queries\n\nimport (\n")
	keys := make([]string, 0, len(imports))
	for k := range imports {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q\n", k)
	}
	b.WriteString(")\n\n")
	b.WriteString(`// ErrNotFound is returned by a :one query that finds no row.
var ErrNotFound = errors.New("queries: not found")

// DB is what queries run on: a *sql.DB, a *sql.Tx or a *sql.Conn.
type DB interface {
	ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error)
	QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error)
	QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row
}

// Queries runs the queries on a database.
type Queries struct {
	db       DB
	postgres bool
}

// New returns the queries for db, a SQLite or PostgreSQL database.
func New(db *sql.DB) (*Queries, error) {
	d, err := sqldb.Detect(db)
	if err != nil {
		return nil, err
	}
	return &Queries{db: db, postgres: d == sqldb.Postgres}, nil
}

// WithTx returns the queries running in tx.
func (q *Queries) WithTx(tx *sql.Tx) *Queries { return &Queries{db: tx, postgres: q.postgres} }

func (q *Queries) text(sqlite, postgres string) string {
	if q.postgres {
		return postgres
	}
	return sqlite
}

`)
	rows := map[string]bool{}
	for _, q := range qs {
		renderQuery(&b, q, rows)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the generated queries: %w\n%s", err, b.String())
	}
	return src, nil
}

func addImport(imports map[string]bool, t string) {
	switch strings.TrimPrefix(t, "*") {
	case "time.Time":
		imports["time"] = true
	case "json.RawMessage":
		imports["encoding/json"] = true
	case "sealed.String", "sealed.Bytes":
		imports["github.com/Unfield/Tern/sealed"] = true
	}
}

func renderQuery(b *bytes.Buffer, q *query, rows map[string]bool) {
	lower := lowerFirst(q.name)
	fmt.Fprintf(b, "const %sSQL = %s\n\n", lower, strconv.Quote(q.sql))
	if pg := sqldb.Postgres.Rebind(q.sql); pg != q.sql {
		fmt.Fprintf(b, "const %sSQLPostgres = %s\n\n", lower, strconv.Quote(pg))
	}
	text := fmt.Sprintf("q.text(%sSQL, %sSQLPostgres)", lower, lower)
	if sqldb.Postgres.Rebind(q.sql) == q.sql {
		text = lower + "SQL"
	}

	// Parameters: arguments, or a struct past three.
	structParams := len(q.params) > 3
	var sig, args []string
	paramsType := q.name + "Params"
	if structParams {
		fmt.Fprintf(b, "// %s are the parameters of %s.\ntype %s struct {\n", paramsType, q.name, paramsType)
		for _, p := range q.params {
			fmt.Fprintf(b, "\t%s %s\n", goName(p.name), p.goType)
		}
		b.WriteString("}\n\n")
		sig = append(sig, "in "+paramsType)
	} else {
		for _, p := range q.params {
			sig = append(sig, lowerName(p.name)+" "+p.goType)
		}
	}
	for _, u := range q.uses {
		p := q.params[u]
		if structParams {
			args = append(args, "in."+goName(p.name))
		} else {
			args = append(args, lowerName(p.name))
		}
	}
	callArgs := ""
	if len(args) > 0 {
		callArgs = ", " + strings.Join(args, ", ")
	}

	// The result.
	result := ""
	single := len(q.columns) == 1
	switch q.kind {
	case kindExec:
		result = "error"
	case kindExecRows:
		result = "(int64, error)"
	default:
		elem := ""
		if single {
			elem = q.columns[0].goType
		} else {
			elem = q.rowType()
			if !rows[elem] {
				rows[elem] = true
				fmt.Fprintf(b, "// %s is a row of %s.\ntype %s struct {\n", elem, q.name, elem)
				for _, c := range q.columns {
					fmt.Fprintf(b, "\t%s %s `json:%q`\n", goName(c.name), c.goType, jsonName(c.name))
				}
				b.WriteString("}\n\n")
			}
		}
		if q.kind == kindMany {
			result = "([]" + elem + ", error)"
		} else {
			result = "(" + elem + ", error)"
		}
	}

	fmt.Fprintf(b, "// %s runs queries/%s:%d.\n", q.name, filepath.Base(q.file), q.line)
	if len(q.doc) > 0 {
		b.WriteString("//\n")
		for _, line := range q.doc {
			fmt.Fprintf(b, "// %s\n", line)
		}
	}
	fmt.Fprintf(b, "func (q *Queries) %s(%s) %s {\n", q.name, strings.Join(append([]string{"ctx context.Context"}, sig...), ", "), result)
	scanInto := func(target string) string {
		if single {
			return "&" + target
		}
		var parts []string
		for _, c := range q.columns {
			parts = append(parts, "&"+target+"."+goName(c.name))
		}
		return strings.Join(parts, ", ")
	}
	switch q.kind {
	case kindExec:
		fmt.Fprintf(b, "\t_, err := q.db.ExecContext(ctx, %s%s)\n\treturn err\n", text, callArgs)
	case kindExecRows:
		fmt.Fprintf(b, "\tres, err := q.db.ExecContext(ctx, %s%s)\n\tif err != nil {\n\t\treturn 0, err\n\t}\n\treturn res.RowsAffected()\n", text, callArgs)
	case kindOne:
		elem := strings.TrimSuffix(strings.TrimPrefix(result, "("), ", error)")
		fmt.Fprintf(b, "\tvar v %s\n\terr := q.db.QueryRowContext(ctx, %s%s).Scan(%s)\n", elem, text, callArgs, scanInto("v"))
		b.WriteString("\tif errors.Is(err, sql.ErrNoRows) {\n\t\treturn v, ErrNotFound\n\t}\n\treturn v, err\n")
	case kindMany:
		elem := strings.TrimSuffix(strings.TrimPrefix(result, "([]"), ", error)")
		fmt.Fprintf(b, "\trows, err := q.db.QueryContext(ctx, %s%s)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\tdefer rows.Close()\n", text, callArgs)
		fmt.Fprintf(b, "\tout := []%s{}\n\tfor rows.Next() {\n\t\tvar v %s\n\t\tif err := rows.Scan(%s); err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\tout = append(out, v)\n\t}\n\treturn out, rows.Err()\n", elem, elem, scanInto("v"))
	}
	b.WriteString("}\n\n")
}

func (q *query) rowType() string {
	if q.row != "" {
		return q.row
	}
	return q.name + "Row"
}

// initialisms are written in capitals in Go names.
var initialisms = map[string]bool{"id": true, "url": true, "uri": true, "http": true, "https": true, "api": true, "json": true, "uuid": true, "ip": true, "sql": true, "html": true, "css": true, "utc": true}

func words(s string) []string {
	var out []string
	for _, w := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == ' ' }) {
		// Split camelCase too: userID, addedAt.
		start := 0
		rs := []rune(w)
		for i := 1; i < len(rs); i++ {
			if unicode.IsUpper(rs[i]) && unicode.IsLower(rs[i-1]) {
				out = append(out, string(rs[start:i]))
				start = i
			}
		}
		out = append(out, string(rs[start:]))
	}
	return out
}

// goName is an exported Go name: user_id is UserID.
func goName(s string) string {
	var b strings.Builder
	for _, w := range words(s) {
		lw := strings.ToLower(w)
		if initialisms[lw] {
			b.WriteString(strings.ToUpper(lw))
			continue
		}
		b.WriteString(strings.ToUpper(lw[:1]) + lw[1:])
	}
	return b.String()
}

// lowerName is a Go parameter name: user_id is userID.
func lowerName(s string) string {
	ws := words(s)
	var b strings.Builder
	for i, w := range ws {
		lw := strings.ToLower(w)
		switch {
		case i == 0:
			b.WriteString(lw)
		case initialisms[lw]:
			b.WriteString(strings.ToUpper(lw))
		default:
			b.WriteString(strings.ToUpper(lw[:1]) + lw[1:])
		}
	}
	name := b.String()
	if goKeywords[name] {
		name += "_"
	}
	return name
}

// jsonName is a JSON field name: user_id is userId.
func jsonName(s string) string {
	ws := words(s)
	var b strings.Builder
	for i, w := range ws {
		lw := strings.ToLower(w)
		if i == 0 {
			b.WriteString(lw)
		} else {
			b.WriteString(strings.ToUpper(lw[:1]) + lw[1:])
		}
	}
	return b.String()
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

var goKeywords = map[string]bool{"break": true, "case": true, "chan": true, "const": true, "continue": true, "default": true, "defer": true, "else": true, "fallthrough": true, "for": true, "func": true, "go": true, "goto": true, "if": true, "import": true, "interface": true, "map": true, "package": true, "range": true, "return": true, "select": true, "struct": true, "switch": true, "type": true, "var": true, "ctx": true, "q": true, "in": true, "err": true, "v": true, "rows": true, "res": true, "out": true}
