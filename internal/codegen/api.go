package codegen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/Unfield/Tern/internal/routes"
)

const apiJS = `// Code generated by tern; DO NOT EDIT.
import { createApi } from '@ternkit/tern';
import { route } from './routes.js';

/** Calls the app's typed endpoints; see $api's types. */
export const api = createApi(route);
`

const apiDTS = `// Code generated by tern; DO NOT EDIT.
// The app's typed endpoints: Go functions such as
// func GET(ctx *kit.Ctx, in Query) (Out, error).

%s

export interface Endpoints {
%s}

type Options<E> = (E extends { params: infer P } ? ({} extends P ? { params?: P } : { params: P }) : {}) &
	(E extends { query: infer Q } ? { query?: Q } : {}) &
	(E extends { body: infer B } ? { body: B } : {}) & {
		/** Cancels the request. */
		signal?: AbortSignal;
		/** Use another fetch, such as one with custom headers. */
		fetch?: typeof fetch;
	};

type Args<E> = {} extends Options<E> ? [options?: Options<E>] : [options: Options<E>];

/**
 * Calls a typed endpoint and returns its decoded JSON response. Failed
 * requests throw an ApiError with the status and the server's message:
 *
 *   const project = await api('GET /api/projects/[id]', { params: { id: 42 } });
 */
export function api<K extends keyof Endpoints>(endpoint: K, ...args: Args<Endpoints[K]>): Promise<Endpoints[K]['response']>;
`

// apiModule writes $api: a typed client for the typed endpoints.
func (g *generator) apiModule() {
	e := newTSEmitter()
	links := linkPatterns(g.m)
	keys := make([]string, 0, len(links))
	for k := range links {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var entries strings.Builder
	for _, pattern := range keys {
		r := links[pattern]
		rp := g.pkgs[r.Dir]
		if rp == nil || len(rp.endpoints) == 0 {
			continue
		}
		methods := make([]string, 0, len(rp.endpoints))
		for m := range rp.endpoints {
			methods = append(methods, m)
		}
		sort.Strings(methods)
		for _, m := range methods {
			sig := rp.endpoints[m]
			var parts []string
			var params []string
			for _, p := range r.Params() {
				switch p.Kind {
				case routes.OptionalParam:
					params = append(params, fmt.Sprintf("%s?: string | number", tsKey(p.Value)))
				case routes.Rest:
					params = append(params, fmt.Sprintf("%s?: string | string[]", tsKey(p.Value)))
				default:
					params = append(params, fmt.Sprintf("%s: string | number", tsKey(p.Value)))
				}
			}
			if len(params) > 0 {
				parts = append(parts, "params: { "+strings.Join(params, "; ")+" }")
			}
			if _, rest := inputFields(sig.in); sig.in != nil && len(rest) > 0 {
				in := e.dataType(sig.in)
				path, _ := inputFields(sig.in)
				if len(path) > 0 {
					var omit []string
					for _, j := range path {
						omit = append(omit, fmt.Sprintf("%q", j))
					}
					sort.Strings(omit)
					in = "Omit<" + in + ", " + strings.Join(omit, " | ") + ">"
				}
				if bodyMethod(m) {
					parts = append(parts, "body: "+in)
				} else {
					parts = append(parts, "query: Partial<"+in+">")
				}
			}
			parts = append(parts, "response: "+e.typeOf(sig.out))
			fmt.Fprintf(&entries, "\t%q: { %s };\n", m+" "+pattern, strings.Join(parts, "; "))
		}
	}
	g.files[GenDir+"/generated/api.js"] = []byte(apiJS)
	g.files[GenDir+"/generated/api.d.ts"] = []byte(fmt.Sprintf(apiDTS, strings.Join(e.decls, "\n\n"), entries.String()))
}
