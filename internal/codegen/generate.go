// Package codegen generates the code that connects a Tern app's routes to
// the runtime: tern.gen.go for the Go server, the client route manifest
// for Vite, and TypeScript types for every route.
package codegen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path"
	"path/filepath"
	"slices"
	"sort"
	"strconv"
	"strings"

	"github.com/Unfield/Tern/internal/i18n"
	"github.com/Unfield/Tern/internal/routes"
)

// Project layout conventions.
const (
	RoutesDir   = "src/routes"
	AppHTML     = "src/app.html"
	GenDir      = ".tern"
	GoFile      = "tern.gen.go"
	ClientEntry = ".tern/generated/client.js"
	ClientOut   = ".tern/output/client"
	ServerEntry = ".tern/generated/server.js"
	ServerOut   = ".tern/output/server"
)

// Result describes what Generate produced.
type Result struct {
	Manifest *routes.Manifest
	// Changed lists the files that were written because their content changed.
	Changed []string
	// GoChanged reports whether Go code changed, so the server must be rebuilt.
	GoChanged bool
	// Prerender reports whether any route is prerendered at build time.
	Prerender bool
	// Warnings are problems that do not stop the build, such as missing
	// translations.
	Warnings []string
}

// Generate scans the project at root and writes all generated files.
// Files whose content is unchanged are not rewritten, so file watchers
// only see real changes.
func Generate(root string) (*Result, error) {
	root, err := filepath.Abs(root)
	if err != nil {
		return nil, err
	}
	m, err := routes.Scan(os.DirFS(root), RoutesDir)
	if err != nil {
		return nil, err
	}
	if _, err := os.Stat(filepath.Join(root, AppHTML)); err != nil {
		return nil, fmt.Errorf("%s is missing: every Tern app needs an HTML template containing %%tern.head%% and %%tern.body%%", AppHTML)
	}
	cfg, err := LoadConfig(root)
	if err != nil {
		return nil, err
	}
	pkgs, err := analyze(root, RoutesDir, m)
	if err != nil {
		return nil, err
	}

	g := &generator{root: root, m: m, pkgs: pkgs, cfg: cfg, files: map[string][]byte{}}
	if err := g.loadLocales(); err != nil {
		return nil, err
	}
	if err := g.goFile(); err != nil {
		return nil, err
	}
	g.clientManifest()
	g.typeFiles()
	g.tsconfig()
	g.files[".tern/ambient.d.ts"] = []byte(ambientTypes)
	g.linksModule()
	g.serverEntry()
	g.files[ClientOut+"/.keep"] = []byte("Placeholder so the client directory can be embedded before the first build.\n")
	g.files[ServerOut+"/.keep"] = []byte("Placeholder so the server directory can be embedded before the first build.\n")

	g.i18nTypes()
	res := &Result{Manifest: m, Warnings: g.warnings}
	for _, rp := range pkgs {
		res.Prerender = res.Prerender || rp.prerender
	}
	for _, name := range sortedKeys(g.files) {
		changed, err := writeIfChanged(filepath.Join(root, filepath.FromSlash(name)), g.files[name])
		if err != nil {
			return nil, err
		}
		if changed {
			res.Changed = append(res.Changed, name)
			if strings.HasSuffix(name, ".go") {
				res.GoChanged = true
			}
		}
	}
	if err := g.removeStaleTypes(); err != nil {
		return nil, err
	}
	return res, nil
}

type generator struct {
	cfg      Config
	locales  *i18n.Catalog
	warnings []string
	root     string
	m        *routes.Manifest
	pkgs     map[string]*routePackage
	files    map[string][]byte

	layoutIndex map[string]int // by dir
	layouts     []routes.Layout
}

// collectLayouts assigns each layout directory a stable index.
func (g *generator) collectLayouts() {
	if g.layoutIndex != nil {
		return
	}
	g.layoutIndex = map[string]int{}
	byDir := map[string]routes.Layout{}
	for _, r := range g.m.Routes {
		for _, l := range r.Layouts {
			byDir[l.Dir] = l
		}
	}
	dirs := sortedKeys(byDir)
	for i, d := range dirs {
		g.layoutIndex[d] = i
		g.layouts = append(g.layouts, byDir[d])
	}
}

func (g *generator) layoutRefs(ls []routes.Layout) []int {
	out := make([]int, len(ls))
	for i, l := range ls {
		out[i] = g.layoutIndex[l.Dir]
	}
	return out
}

// rootLayouts are the layouts used for URLs that match no route.
func (g *generator) rootLayouts() []routes.Layout {
	for _, l := range g.layouts {
		if l.Dir == "" {
			return []routes.Layout{l}
		}
	}
	return nil
}

func (g *generator) goFile() error {
	g.collectLayouts()
	pkgName, err := rootPackageName(g.root)
	if err != nil {
		return err
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tern; DO NOT EDIT.\n\npackage %s\n\nimport (\n\t\"embed\"\n\t\"io/fs\"\n\n\t\"github.com/Unfield/Tern/kit\"\n", pkgName)
	aliases := map[string]*routePackage{}
	for _, rp := range g.pkgs {
		aliases[rp.alias] = rp
	}
	if len(aliases) > 0 {
		b.WriteString("\n")
	}
	for _, alias := range sortedKeys(aliases) {
		fmt.Fprintf(&b, "\t%s %s\n", alias, strconv.Quote(aliases[alias].pkgPath))
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "//go:embed %s\nvar ternAppHTML string\n\n", AppHTML)
	fmt.Fprintf(&b, "//go:embed all:%s\nvar ternClientFS embed.FS\n\n", ClientOut)
	fmt.Fprintf(&b, "//go:embed all:%s\nvar ternServerFS embed.FS\n\n", ServerOut)
	if g.locales != nil {
		fmt.Fprintf(&b, "//go:embed %s\nvar ternLocalesFS embed.FS\n\n", LocalesDir)
	}

	b.WriteString("var ternManifest = &kit.Manifest{\n")
	fmt.Fprintf(&b, "\tAppHTML: ternAppHTML,\n\tClientEntry: %q,\n", ClientEntry)
	if g.cfg.BasePath != "" {
		fmt.Fprintf(&b, "\tBasePath: %q,\n", g.cfg.BasePath)
	}
	if g.locales != nil {
		fmt.Fprintf(&b, "\tDefaultLocale: %q,\n", g.locales.Default)
	}
	b.WriteString("\tLayouts: []kit.LayoutDef{\n")
	for _, l := range g.layouts {
		fmt.Fprintf(&b, "\t\t{Dir: %q", l.Dir)
		if l.Component != "" {
			fmt.Fprintf(&b, ", Component: %q", routeFile(l.Component))
		}
		if l.Go != nil {
			fmt.Fprintf(&b, ", Load: kit.LoadOf(%s.LayoutLoad)", g.pkgs[l.Go.Dir].alias)
		}
		b.WriteString("},\n")
	}
	b.WriteString("\t},\n\tRoutes: []kit.RouteDef{\n")
	for _, r := range g.m.Routes {
		fmt.Fprintf(&b, "\t\t{\n\t\t\tID: %q,\n", r.ID)
		if refs := g.layoutRefs(r.Layouts); len(refs) > 0 {
			fmt.Fprintf(&b, "\t\t\tLayouts: %s,\n", goInts(refs))
		}
		var rp *routePackage
		if r.Go != nil {
			rp = g.pkgs[r.Go.Dir]
		}
		if r.Page != "" {
			fmt.Fprintf(&b, "\t\t\tPage: &kit.PageDef{Component: %q", routeFile(r.Page))
			if rp != nil && rp.load != nil {
				fmt.Fprintf(&b, ", Load: kit.LoadOf(%s.Load)", rp.alias)
			}
			if r.HasActions() {
				fmt.Fprintf(&b, ", Actions: %s.Actions", rp.alias)
			}
			if rp != nil && rp.noSSR {
				b.WriteString(", NoSSR: true")
			}
			b.WriteString("},\n")
		}
		if rp != nil && rp.prerender && (r.Page != "" || slices.Contains(rp.methods, "GET")) {
			b.WriteString("\t\t\tPrerender: true,\n")
		}
		if rp != nil && rp.entries {
			fmt.Fprintf(&b, "\t\t\tEntries: %s.Entries,\n", rp.alias)
		}
		if rp != nil && len(rp.methods) > 0 {
			b.WriteString("\t\t\tEndpoint: map[string]kit.HandlerFunc{\n")
			for _, m := range rp.methods {
				fmt.Fprintf(&b, "\t\t\t\t%q: %s.%s,\n", m, rp.alias, m)
			}
			b.WriteString("\t\t\t},\n")
		}
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t},\n")
	if refs := g.layoutRefs(g.rootLayouts()); len(refs) > 0 {
		fmt.Fprintf(&b, "\tFallback: kit.FallbackDef{Layouts: %s},\n", goInts(refs))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, `func init() {
	client, err := fs.Sub(ternClientFS, %q)
	if err != nil {
		panic(err)
	}
	ternManifest.Client = client
	if bundle, err := fs.ReadFile(ternServerFS, %q); err == nil {
		ternManifest.ServerBundle = string(bundle)
	}
%s}

// ternApp creates the Tern application. Options configure hooks,
// middleware, matchers and more; see the kit package.
func ternApp(opts ...kit.Option) (*kit.App, error) {
	return kit.New(ternManifest, opts...)
}
`, ClientOut, ServerOut+"/server.js", g.localesInit())

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("codegen: formatting %s: %w\n%s", GoFile, err, b.String())
	}
	g.files[GoFile] = src
	return nil
}

// ServiceWorkerSources are the files that define an app's service worker.
var ServiceWorkerSources = []string{"src/service-worker.ts", "src/service-worker.js"}

// serviceWorker returns the app's service worker source, or "".
func (g *generator) serviceWorker() string { return FindServiceWorker(g.root) }

// FindServiceWorker returns the service worker source in root, or "".
func FindServiceWorker(root string) string {
	for _, f := range ServiceWorkerSources {
		if _, err := os.Stat(filepath.Join(root, f)); err == nil {
			return f
		}
	}
	return ""
}

func (g *generator) localesInit() string {
	if g.locales == nil {
		return ""
	}
	return fmt.Sprintf("\tlocales, err := fs.Sub(ternLocalesFS, %q)\n\tif err != nil {\n\t\tpanic(err)\n\t}\n\tternManifest.Locales = locales\n", LocalesDir)
}

// rootPackageName returns the package name used by the project root's Go
// files, defaulting to main.
func rootPackageName(root string) (string, error) {
	entries, err := os.ReadDir(root)
	if err != nil {
		return "", err
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == GoFile {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(root, name), nil, parser.PackageClauseOnly)
		if err != nil {
			return "", err
		}
		return f.Name.Name, nil
	}
	return "main", nil
}

// clientManifest writes the route manifest and entry module for the client.
func (g *generator) clientManifest() {
	g.collectLayouts()
	imp := func(rel string) string {
		return fmt.Sprintf("() => import(%q)", "../../"+routeFile(rel))
	}

	var b strings.Builder
	b.WriteString("// Code generated by tern; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "export const base = %q;\n", g.cfg.BasePath)
	register := g.serviceWorker() != "" && (g.cfg.ServiceWorker.Register == nil || *g.cfg.ServiceWorker.Register)
	fmt.Fprintf(&b, "export const serviceWorker = %t;\n\n", register)
	b.WriteString("export const layouts = [\n")
	for _, l := range g.layouts {
		comp := "null"
		if l.Component != "" {
			comp = imp(l.Component)
		}
		fmt.Fprintf(&b, "\t{ dir: %q, component: %s, hasLoad: %t },\n", l.Dir, comp, l.Go != nil)
	}
	b.WriteString("];\n\n")

	errorList := func(errs []string, ls []routes.Layout) string {
		var parts []string
		for _, e := range errs {
			parts = append(parts, fmt.Sprintf("{ layouts: %d, component: %s }", layoutsAbove(e, ls), imp(e)))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	}

	b.WriteString("export const routes = {\n")
	for _, r := range g.m.Routes {
		if r.Page == "" {
			continue
		}
		fmt.Fprintf(&b, "\t%q: {\n\t\tlayouts: %s,\n\t\tpage: %s,\n\t\thasLoad: %t,\n\t\terrors: %s,\n\t},\n",
			r.ID, intSlice(g.layoutRefs(r.Layouts)), imp(r.Page), r.HasLoad(), errorList(r.ErrorPages, r.Layouts))
	}
	b.WriteString("};\n\n")

	rl := g.rootLayouts()
	fmt.Fprintf(&b, "export const fallback = { layouts: %s, errors: %s };\n\n", intSlice(g.layoutRefs(rl)), errorList(g.rootErrorPages(), rl))
	b.WriteString(g.i18nClient())
	g.files[".tern/generated/manifest.js"] = []byte(b.String())

	g.files[ClientEntry] = []byte(`// Code generated by tern; DO NOT EDIT.

import { start } from '@ternkit/tern/client';
import * as manifest from './manifest.js';

start(manifest);
`)
}

// serverEntry writes the module Vite bundles into the server renderer. It
// imports every component statically: the renderer is one file.
func (g *generator) serverEntry() {
	g.collectLayouts()
	var b strings.Builder
	b.WriteString("// Code generated by tern; DO NOT EDIT.\n\n")
	b.WriteString("import '@ternkit/tern/polyfills';\nimport { createRenderer } from '@ternkit/tern/server';\n")
	i18nImports, i18nConfig := g.i18nServer()
	b.WriteString(i18nImports)

	names := map[string]string{}
	name := func(rel string) string {
		if n, ok := names[rel]; ok {
			return n
		}
		n := fmt.Sprintf("C%d", len(names))
		names[rel] = n
		fmt.Fprintf(&b, "import %s from %q;\n", n, "../../"+routeFile(rel))
		return n
	}
	var body strings.Builder
	body.WriteString("\nexport const render = createRenderer({\n\tlayouts: [\n")
	for _, l := range g.layouts {
		comp := "null"
		if l.Component != "" {
			comp = name(l.Component)
		}
		fmt.Fprintf(&body, "\t\t{ component: %s },\n", comp)
	}
	body.WriteString("\t],\n")

	errorList := func(errs []string, ls []routes.Layout) string {
		var parts []string
		for _, e := range errs {
			parts = append(parts, fmt.Sprintf("{ layouts: %d, component: %s }", layoutsAbove(e, ls), name(e)))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	}
	body.WriteString("\troutes: {\n")
	for _, r := range g.m.Routes {
		if r.Page == "" {
			continue
		}
		fmt.Fprintf(&body, "\t\t%q: { layouts: %s, page: %s, errors: %s },\n",
			r.ID, intSlice(g.layoutRefs(r.Layouts)), name(r.Page), errorList(r.ErrorPages, r.Layouts))
	}
	body.WriteString("\t},\n")
	rl := g.rootLayouts()
	fmt.Fprintf(&body, "\tfallback: { layouts: %s, errors: %s },\n\ti18n: %s\n});\n\nglobalThis.__tern_render = render;\n",
		intSlice(g.layoutRefs(rl)), errorList(g.rootErrorPages(), rl), i18nConfig)

	b.WriteString(body.String())
	g.files[ServerEntry] = []byte(b.String())
}

// layoutsAbove counts the layouts that wrap an error page.
func layoutsAbove(errorPage string, ls []routes.Layout) int {
	dir := path.Dir(errorPage)
	if dir == "." {
		dir = ""
	}
	n := 0
	for _, l := range ls {
		if l.Dir == "" || l.Dir == dir || strings.HasPrefix(dir, l.Dir+"/") {
			n++
		}
	}
	return n
}

func (g *generator) rootErrorPages() []string {
	for _, r := range g.m.Routes {
		for _, e := range r.ErrorPages {
			if path.Dir(e) == "." {
				return []string{e}
			}
		}
	}
	return nil
}

