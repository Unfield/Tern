package codegen

import (
	"fmt"
	"go/types"
	"path"
	"strings"

	"github.com/Unfield/Tern/internal/routes"
)

const typesPrelude = `// Code generated by tern; DO NOT EDIT.

import type { Snippet } from 'svelte';

type Expand<T> = T extends infer O ? { [K in keyof O]: O[K] } : never;
type Merge<A, B> = Expand<Omit<A, keyof B> & B>;
type OptionalUnion<U extends Record<string, unknown>, A extends keyof U = U extends U ? keyof U : never> =
	U extends unknown ? { [P in Exclude<A, keyof U>]?: never } & U : never;
`

// dirTypes collects what a route directory's $types.d.ts must describe.
type dirTypes struct {
	dir    string
	layout []routes.Layout // layout chain ending at this dir, if it has a layout
	route  *routes.Route   // the route whose page is in this dir, if any
}

func (g *generator) typeFiles() {
	dirs := map[string]*dirTypes{}
	get := func(dir string) *dirTypes {
		if d, ok := dirs[dir]; ok {
			return d
		}
		d := &dirTypes{dir: dir}
		dirs[dir] = d
		return d
	}
	for _, r := range g.m.Routes {
		for i, l := range r.Layouts {
			get(l.Dir).layout = r.Layouts[:i+1]
		}
		if r.Page != "" || r.IsEndpoint() {
			get(r.Dir).route = r
		}
	}
	for _, dir := range sortedKeys(dirs) {
		name := path.Join(GenDir, "types", RoutesDir, dir, "$types.d.ts")
		g.files[name] = []byte(g.renderTypes(dirs[dir]))
	}
}

// layoutData returns the TS type of the data merged from a chain of layouts.
func (g *generator) layoutData(e *tsEmitter, chain []routes.Layout) string {
	out := "{}"
	for _, l := range chain {
		if l.Go == nil {
			continue
		}
		rp := g.pkgs[l.Go.Dir]
		if rp == nil || rp.layoutLoad == nil {
			continue
		}
		out = fmt.Sprintf("Merge<%s, %s>", out, e.dataType(rp.layoutLoad))
	}
	return out
}

func (g *generator) renderTypes(d *dirTypes) string {
	e := newTSEmitter()
	var b strings.Builder

	if d.route != nil {
		b.WriteString("export type RouteParams = ")
		b.WriteString(paramsType(d.route))
		b.WriteString(";\n")
	}

	if len(d.layout) > 0 {
		parent := g.layoutData(e, d.layout[:len(d.layout)-1])
		own := "{}"
		if l := d.layout[len(d.layout)-1]; l.Go != nil {
			if rp := g.pkgs[l.Go.Dir]; rp != nil && rp.layoutLoad != nil {
				own = e.dataType(rp.layoutLoad)
			}
		}
		fmt.Fprintf(&b, "export type LayoutParentData = Expand<%s>;\n", parent)
		fmt.Fprintf(&b, "export type LayoutServerData = %s;\n", own)
		b.WriteString("export type LayoutData = Merge<LayoutParentData, LayoutServerData>;\n")
		b.WriteString("export type LayoutProps = { data: LayoutData; children: Snippet };\n")
	}

	if r := d.route; r != nil && r.Page != "" {
		layoutData := g.layoutData(e, r.Layouts)
		own := "{}"
		var rp *routePackage
		if r.Go != nil {
			rp = g.pkgs[r.Go.Dir]
		}
		if rp != nil && rp.load != nil {
			own = e.dataType(rp.load)
		}
		fmt.Fprintf(&b, "export type PageServerData = %s;\n", own)
		fmt.Fprintf(&b, "export type PageData = Merge<%s, PageServerData>;\n", layoutData)
		fmt.Fprintf(&b, "export type ActionData = %s;\n", actionData(e, rp))
		b.WriteString("export type PageProps = { data: PageData; form: ActionData };\n")
	}

	var out strings.Builder
	out.WriteString(typesPrelude)
	for _, decl := range e.decls {
		out.WriteString("\n")
		out.WriteString(decl)
		out.WriteString("\n")
	}
	out.WriteString("\n")
	out.WriteString(b.String())
	return out.String()
}

func paramsType(r *routes.Route) string {
	params := r.Params()
	if len(params) == 0 {
		return "Record<string, never>"
	}
	var parts []string
	for _, p := range params {
		opt := ""
		if p.Kind == routes.OptionalParam {
			opt = "?"
		}
		parts = append(parts, fmt.Sprintf("%s%s: string", tsKey(p.Value), opt))
	}
	return "{ " + strings.Join(parts, "; ") + " }"
}

// actionData is the type of the page's `form` prop: the result of the last
// action, or null before any action ran.
func actionData(e *tsEmitter, rp *routePackage) string {
	if rp == nil || (len(rp.actions) == 0 && len(rp.failures) == 0 && !rp.actionsAny) {
		return "null"
	}
	var members []string
	seen := map[string]bool{}
	add := func(t types.Type) {
		ts := e.dataType(t)
		if !seen[ts] {
			seen[ts] = true
			members = append(members, ts)
		}
	}
	for _, t := range rp.actions {
		add(t)
	}
	for _, t := range rp.failures {
		add(t)
	}
	if rp.actionsAny {
		members = append(members, "Record<string, unknown>")
	}
	if len(members) == 0 {
		return "null"
	}
	return fmt.Sprintf("Expand<OptionalUnion<%s>> | null", strings.Join(members, " | "))
}
