// Problem is something the compiler couldn't compile. The code compiles
// to a stub that raises js.Unsupported when it runs, so only a request that
// reaches it falls back to the JavaScript engine.
type Problem struct {
	Module string
	Offset int
	What   string
}

func (p Problem) String() string { return fmt.Sprintf("%s:%d: %s", p.Module, p.Offset, p.What) }

// Result is a compiled app.
type Result struct {
	// Source is the Go file, package native.
	Source []byte
	// Problems lists what couldn't be compiled, in module order.
	Problems []Problem
	// Modules is how many modules were compiled.
	Modules int
	// Mismatches lists the intrinsics not used because the function they
	// stand for has changed, with its fingerprint now.
	Mismatches []string
}

// nativeModules are the imports Go provides, by specifier.
var nativeModules = map[string]string{
	"svelte/internal/server": "js.NewNamespace()",
	"svelte/server":          "js.NewNamespace()",
	"svelte":                 "js.NewNamespace()",
	"esm-env":                "js.NewNamespace()",
}

type module struct {
	id      string
	index   int
	ast     *Node
	imports map[string]*string
	goType  string // m3
	goVar   string // M3
	scope   *scope
	// exports maps export names to the Go expression of their binding.
	exports map[string]string
	// starFrom lists modules whose exports `export * from` re-exports.
	starFrom []*module
	// zero is the module struct's initial value: every binding undefined.
	zero     string
	resolved bool
}

// Compiler turns the IR into Go.
type Compiler struct {
	mismatches []string
	globalRefs int
	ics        int
	ir         *IR
	mods       map[string]*module
	order      []*module
	problems   []Problem
	tmp        int
	cur        *module
}

// Compile compiles every module reachable from the IR's entry.
func Compile(ir *IR) (*Result, error) {
	c := &Compiler{ir: ir, mods: map[string]*module{}}
	for i, m := range ir.Modules {
		c.mods[m.ID] = &module{id: m.ID, index: i, ast: m.AST, imports: m.Imports, goType: "m" + strconv.Itoa(i), goVar: "r.M" + strconv.Itoa(i)}
	}
	entry, ok := c.mods[ir.Entry]
	if !ok {
		return nil, fmt.Errorf("native: the entry %s is not in the IR", ir.Entry)
	}
	c.visit(entry, map[*module]bool{})
	for _, m := range c.order {
		c.declareModule(m)
	}
	for _, m := range c.order {
		c.resolveExports(m, map[*module]bool{})
	}
	var b strings.Builder
	b.WriteString("// Code generated by tern build from the server build's modules. DO NOT EDIT.\n\n")
	b.WriteString("package native\n\nimport (\n\t\"github.com/Unfield/Tern/native/js\"\n\t\"github.com/Unfield/Tern/native/svelte\"\n)\n\n")
	b.WriteString("var _ = svelte.Escape\n\n")
	var mods strings.Builder
	for _, m := range c.order {
		c.cur = m
		mods.WriteString(c.compileModule(m))
	}
	// The realm holds everything that changes: the modules' variables and
	// the caches. Each realm runs on its own.
	b.WriteString("// realm is a js.Realm with the app's modules in it.\ntype realm struct {\n\t*js.Realm\n")
	for _, m := range c.order {
		fmt.Fprintf(&b, "\t%s %s\n", strings.TrimPrefix(m.goVar, "r."), m.goType)
	}
	fmt.Fprintf(&b, "\tics     [%d]js.IC\n\tglobals [%d]js.GlobalRef\n}\n\n", c.ics, c.globalRefs)
	b.WriteString("// New makes a realm and evaluates the app's modules in it, in the order\n// JavaScript would.\nfunc New() *js.Realm {\n\tr := &realm{Realm: js.NewRealm()}\n")
	for _, m := range c.order {
		fmt.Fprintf(&b, "\tr.%s = %s\n", strings.TrimPrefix(m.goVar, "r."), m.zero)
	}
	for _, m := range c.order {
		fmt.Fprintf(&b, "\tr.init%d()\n", m.index)
	}
	b.WriteString("\treturn r.Realm\n}\n\n")
	b.WriteString(realmCalls(mods.String()))
	src := []byte(b.String())
	formatted, err := format.Source(src)
	if err != nil {
		return &Result{Source: src, Problems: c.problems, Modules: len(c.order)}, fmt.Errorf("native: generated Go doesn't parse: %w", err)
	}
	sort.SliceStable(c.problems, func(i, j int) bool { return c.mods[c.problems[i].Module].index < c.mods[c.problems[j].Module].index })
	return &Result{Source: formatted, Problems: c.problems, Modules: len(c.order), Mismatches: c.mismatches}, nil
}

// visit orders modules as ESM evaluates them: each module after its imports.
func (c *Compiler) visit(m *module, seen map[*module]bool) {
	if seen[m] {
		return
	}
	seen[m] = true
	for _, n := range m.ast.List("body") {
		switch n.Type {
		case "ImportDeclaration", "ExportAllDeclaration", "ExportNamedDeclaration":
			src := n.Child("source")
			if src == nil {
				continue
			}
			if dep := c.resolveModule(m, src.Str("value")); dep != nil {
				c.visit(dep, seen)
			}
		}
	}
	c.order = append(c.order, m)
}

// resolveModule is the recorded module an import resolves to, or nil for native
// modules and ones the IR doesn't have.
func (c *Compiler) resolveModule(m *module, spec string) *module {
	id, ok := m.imports[spec]
	if !ok || id == nil {
		return nil
	}
	return c.mods[*id]
}

func (c *Compiler) problem(n *Node, format string, args ...any) {
	off := 0
	if n != nil {
		off = n.Start
	}
	c.problems = append(c.problems, Problem{Module: c.cur.id, Offset: off, What: fmt.Sprintf(format, args...)})
}

func (c *Compiler) temp(prefix string) string {
	c.tmp++
	return prefix + strconv.Itoa(c.tmp)
}

// goIdent makes a JavaScript identifier into a Go one: v_ plus the name,
// with $ as _S.
func goIdent(name string) string {
	var b strings.Builder
	b.WriteString("v_")
	for _, r := range name {
		switch {
		case r == '$':
			b.WriteString("_S")
		case r == '_' || r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z':
			b.WriteRune(r)
		default:
			fmt.Fprintf(&b, "_u%x_", r)
		}
	}
	return b.String()
}

// quote is a Go string literal holding the exact bytes of s, including
// WTF-8 surrogates.
func quote(s string) string { return strconv.Quote(s) }

// realmNames are the names of js.Realm's exported methods and fields:
// compiled code reaches them through its realm, r.
var realmNames = func() map[string]bool {
	out := map[string]bool{}
	t := reflect.TypeOf(&js.Realm{})
	for i := range t.NumMethod() {
		out[t.Method(i).Name] = true
	}
	for i := range t.Elem().NumField() {
		if f := t.Elem().Field(i); f.IsExported() {
			out[f.Name] = true
		}
	}
	return out
}()

var jsName = regexp.MustCompile(`\bjs\.([A-Z][A-Za-z0-9]*)`)

// realmCalls rewrites js.Name to r.Name where Name belongs to the realm,
// and points the caches at the realm's.
func realmCalls(src string) string {
	src = jsName.ReplaceAllStringFunc(src, func(m string) string {
		if realmNames[m[3:]] {
			return "r." + m[3:]
		}
		return m
	})
	src = strings.ReplaceAll(src, "&ics[", "&r.ics[")
	return strings.ReplaceAll(src, "&globals[", "&r.globals[")
}
