package codegen

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/Unfield/Tern/goscript"
)

// LiveDir holds the Go packages of live components (<script lang="go"
// live>), which are compiled into the app's binary.
const LiveDir = ".tern/goscript/live"

var goScriptRe = regexp.MustCompile(`<script\b([^>]*\blang=["']go["'][^>]*)>([\s\S]*?)</script>`)
var liveAttrRe = regexp.MustCompile(`(^|\s)live(\s|=|$)`)
var packageRe = regexp.MustCompile(`(?m)^\s*package\s+\w+\s*$`)

type liveComponent struct {
	id   string
	file string // absolute
	src  string
	line int
}

// GoScriptID is a component's ID for its path relative to the app root;
// it matches componentID in packages/tern/src/vite/goscript.ts.
func GoScriptID(rel string) string { return goScriptID(rel) }

func goScriptID(rel string) string { return goscript.ComponentID(rel) }

// liveComponents finds the live Go components in src.
func (g *generator) liveComponents() ([]liveComponent, error) {
	var out []liveComponent
	err := filepath.WalkDir(filepath.Join(g.root, "src"), func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil //nolint:nilerr // an unreadable directory has no components
		}
		if d.IsDir() && (strings.HasPrefix(d.Name(), ".") || d.Name() == "node_modules") {
			return filepath.SkipDir
		}
		if d.IsDir() || !strings.HasSuffix(p, ".svelte") {
			return nil
		}
		raw, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		text := string(raw)
		m := goScriptRe.FindStringSubmatchIndex(text)
		if m == nil {
			return nil
		}
		if !liveAttrRe.MatchString(text[m[2]:m[3]]) {
			g.webAssembly = true // runs in the browser, compiled to WebAssembly
			return nil
		}
		rel, _ := filepath.Rel(g.root, p)
		codeStart := m[4]
		out = append(out, liveComponent{
			id:   goScriptID(rel),
			file: p,
			src:  text[m[4]:m[5]],
			line: strings.Count(text[:codeStart], "\n") + 1,
		})
		return nil
	})
	sort.Slice(out, func(i, j int) bool { return out[i].id < out[j].id })
	return out, err
}

// livePackages writes each live component's Go code as a package and
// returns their import paths by ID.
func (g *generator) livePackages(comps []liveComponent, module string) map[string]string {
	imports := map[string]string{}
	for _, c := range comps {
		body := packageRe.ReplaceAllString(c.src, "")
		g.files[LiveDir+"/"+c.id+"/component.go"] = []byte(fmt.Sprintf("// Code generated by tern from <script lang=\"go\" live>; DO NOT EDIT.\n\npackage %s\n\n//line %s:%d\n%s\n", c.id, c.file, c.line, body))
		imports[c.id] = module + "/" + LiveDir + "/" + c.id
	}
	return imports
}

var moduleRe = regexp.MustCompile(`(?m)^module\s+(\S+)`)

func modulePath(root string) (string, error) {
	raw, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", err
	}
	m := moduleRe.FindSubmatch(raw)
	if m == nil {
		return "", fmt.Errorf("codegen: go.mod has no module line")
	}
	return string(m[1]), nil
}
