// Experimental <script lang="go"> support: Go component logic compiled to
// WebAssembly. Enabled with "experimental": { "goScript": true } in
// tern.json. See docs/experimental-go-script.md.
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { promisify } from 'node:util';
import type { PreprocessorGroup } from 'svelte/compiler';
import type { Plugin, ResolvedConfig } from 'vite';

const run = promisify(execFile);
const DIR = '.tern/goscript';
/** The WebAssembly components' Go packages; live ones are written by tern gen. */
const WASM_DIR = '.tern/goscript/wasm';
const GO_SCRIPT = /<script\b([^>]*\blang=["']go["'][^>]*)>([\s\S]*?)<\/script>/;

export function goScriptEnabled(root: string): boolean {
	try {
		const c = JSON.parse(fs.readFileSync(path.join(root, 'tern.json'), 'utf8')) as { experimental?: { goScript?: boolean } };
		return c.experimental?.goScript === true;
	} catch {
		return false;
	}
}

interface GoComponent {
	id: string;
	live: boolean;
	file: string; // absolute .svelte path
	source: string; // the Go code
	line: number; // line of the code's first line in the .svelte file
}

/** A component's ID: stable for its path, valid in Go and JS. */
function componentID(root: string, file: string): string {
	return 'c' + createHash('sha256').update(path.relative(root, file).split(path.sep).join('/')).digest('hex').slice(0, 10);
}

function walk(dir: string, out: string[] = []): string[] {
	let entries: fs.Dirent[];
	try {
		entries = fs.readdirSync(dir, { withFileTypes: true });
	} catch {
		return out;
	}
	for (const e of entries) {
		if (e.name.startsWith('.') || e.name === 'node_modules') continue;
		const p = path.join(dir, e.name);
		if (e.isDirectory()) walk(p, out);
		else if (e.name.endsWith('.svelte')) out.push(p);
	}
	return out;
}

function scan(root: string): GoComponent[] {
	const out: GoComponent[] = [];
	for (const file of walk(path.join(root, 'src'))) {
		const text = fs.readFileSync(file, 'utf8');
		const m = GO_SCRIPT.exec(text);
		if (!m) continue;
		const codeStart = m.index + m[0].indexOf('>') + 1;
		const live = /(^|\s)live(\s|=|$)/.test(m[1]!);
		out.push({ id: componentID(root, file), live, file, source: m[2]!, line: text.slice(0, codeStart).split('\n').length });
	}
	return out.sort((a, b) => a.id.localeCompare(b.id));
}

/** The names a component's Go code shows in its markup. */
export function exportedNames(source: string): { values: string[]; funcs: string[] } {
	const values = [
		...source.matchAll(/\b(?:State|Derived)(?:\[[^\]]*\])?\(\s*\w+\s*,\s*"([A-Za-z_$][\w$]*)"/g),
		...source.matchAll(/\.Show\(\s*\w+\s*,\s*"([A-Za-z_$][\w$]*)"/g)
	].map((m) => m[1]!);
	const funcs = [...source.matchAll(/\.Func\(\s*"([A-Za-z_$][\w$]*)"/g)].map((m) => m[1]!);
	return { values: [...new Set(values)], funcs: [...new Set(funcs)] };
}

function modulePath(root: string): string {
	const mod = /^module\s+(\S+)/m.exec(fs.readFileSync(path.join(root, 'go.mod'), 'utf8'));
	if (!mod) throw new Error('tern: go.mod has no module line');
	return mod[1]!;
}

/** Writes the Go packages, builds the WebAssembly module and computes initial states. */
async function compile(root: string, wasm: boolean): Promise<void> {
	// Live components run on the server: tern gen compiles them into the app.
	const comps = scan(root).filter((c) => !c.live);
	const dir = path.join(root, DIR);
	const pkgDir = path.join(root, WASM_DIR);
	fs.rmSync(pkgDir, { recursive: true, force: true });
	fs.mkdirSync(pkgDir, { recursive: true });
	if (comps.length === 0) {
		fs.writeFileSync(path.join(dir, 'initial.json'), '{}');
		return;
	}
	const mod = modulePath(root);
	let main = '// Code generated by tern from <script lang="go">; DO NOT EDIT.\n\npackage main\n\nimport (\n\t"github.com/Unfield/Tern/goscript"\n';
	for (const c of comps) {
		const body = c.source.replace(/^\s*package\s+\w+\s*$/m, '');
		fs.mkdirSync(path.join(pkgDir, c.id), { recursive: true });
		// //line makes compile errors point at the .svelte file.
		fs.writeFileSync(path.join(pkgDir, c.id, 'component.go'), `package ${c.id}\n\n//line ${c.file}:${c.line}\n${body}\n`);
		main += `\t${c.id} "${mod}/${WASM_DIR}/${c.id}"\n`;
	}
	main += ')\n\nfunc main() {\n';
	for (const c of comps) main += `\tgoscript.Register(${JSON.stringify(c.id)}, ${c.id}.Setup)\n`;
	main += '\tgoscript.Run()\n}\n';
	fs.writeFileSync(path.join(pkgDir, 'main.go'), main);

	const goErr = (e: unknown) => {
		const err = e as { stderr?: string; message: string };
		return new Error(`tern: compiling <script lang="go">:\n${(err.stderr || err.message).trim()}`);
	};
	// Setup runs natively once, so server rendering shows the initial state.
	try {
		const { stdout } = await run('go', ['run', './' + WASM_DIR], { cwd: root, maxBuffer: 16 << 20 });
		fs.writeFileSync(path.join(dir, 'initial.json'), stdout);
	} catch (e) {
		throw goErr(e);
	}
	if (!wasm) return;
	try {
		await run('go', ['build', '-trimpath', '-ldflags=-s -w', '-o', path.join(DIR, 'app.wasm'), './' + WASM_DIR], {
			cwd: root,
			env: { ...process.env, GOOS: 'js', GOARCH: 'wasm' }
		});
		const { stdout: goroot } = await run('go', ['env', 'GOROOT']);
		const candidates = ['lib/wasm/wasm_exec.js', 'misc/wasm/wasm_exec.js'].map((p) => path.join(goroot.trim(), p));
		const execJS = candidates.find((p) => fs.existsSync(p));
		if (!execJS) throw new Error('tern: wasm_exec.js was not found in GOROOT');
		fs.copyFileSync(execJS, path.join(dir, 'wasm_exec.js'));
	} catch (e) {
		throw goErr(e);
	}
}

function initialState(root: string, id: string): Record<string, unknown> {
	try {
		const all = JSON.parse(fs.readFileSync(path.join(root, DIR, 'initial.json'), 'utf8')) as Record<string, Record<string, unknown>>;
		return all[id] ?? {};
	} catch {
		return {};
	}
}

/** Replaces <script lang="go"> with the JavaScript that binds it to Go. */
export function goScriptPreprocessor(getRoot: () => string): PreprocessorGroup {
	return {
		name: 'tern-goscript',
		markup({ content }) {
			// A live component carries its server-rendered state in the page,
			// so hydration starts from the same values.
			const m = GO_SCRIPT.exec(content);
			if (!m || !/(^|\s)live(\s|=|$)/.test(m[1]!)) return;
			return { code: content + '\n<svelte:head>{@html __go.stateScript}</svelte:head>\n' };
		},
		script({ content, attributes, filename }) {
			if (attributes.lang !== 'go' || !filename) return;
			const root = getRoot();
			if (!goScriptEnabled(root)) {
				throw new Error(`${filename}: <script lang="go"> is experimental; enable it with "experimental": { "goScript": true } in tern.json`);
			}
			const id = componentID(root, filename);
			const { values, funcs } = exportedNames(content);
			const { lang: _lang, live, ...rest } = attributes;
			if (live) {
				let code = `
	import { useLive } from '@ternkit/tern/goscript';
	let __goProps = $props();
	const __goUID = $props.id();
	const __go = useLive(${JSON.stringify(id)}, __goUID, () => ({ ...__goProps }));
`;
				for (const v of values) code += `\tconst ${v} = $derived(__go.state[${JSON.stringify(v)}] as any);\n`;
				for (const f of funcs) code += `\tconst ${f} = (...args: unknown[]): any => __go.call(${JSON.stringify(f)}, ...args);\n`;
				return { code, attributes: { ...rest, lang: 'ts' } };
			}
			const base = path.join(root, DIR).split(path.sep).join('/');
			let code = `
	import { useGo } from '@ternkit/tern/goscript';
	import __goWasm from '${base}/app.wasm?url';
	let __goProps = $props();
	const __go = useGo(${JSON.stringify(id)}, ${JSON.stringify(initialState(root, id))}, () => import('${base}/wasm_exec.js'), __goWasm, () => ({ ...__goProps }));
`;
			for (const v of values) code += `\tconst ${v} = $derived(__go.state[${JSON.stringify(v)}] as any);\n`;
			for (const f of funcs) code += `\tconst ${f} = (...args: unknown[]): any => __go.call(${JSON.stringify(f)}, ...args);\n`;
			return { code, attributes: { ...rest, lang: 'ts' } };
		}
	};
}

/** Builds the Go code at startup and on changes. */
export function goScriptPlugin(getRoot: () => string): Plugin {
	let config: ResolvedConfig;
	let enabled = false;
	return {
		name: 'tern:goscript',
		configResolved(c) {
			config = c;
			enabled = goScriptEnabled(c.root);
		},
		async buildStart() {
			if (!enabled) return;
			const ssr = !!config.build.ssr;
			const swBuild = process.env.TERN_SW_BUILD === '1';
			if (swBuild) return;
			// The server build only needs the initial state, which the client
			// build already computed.
			if (ssr && fs.existsSync(path.join(config.root, DIR, 'initial.json'))) return;
			await compile(config.root, !ssr);
		},
		configureServer(server) {
			if (!enabled) return;
			let timer: ReturnType<typeof setTimeout> | undefined;
			server.watcher.on('change', (file) => {
				if (!file.endsWith('.svelte') || !GO_SCRIPT.test(fs.readFileSync(file, 'utf8'))) return;
				clearTimeout(timer);
				timer = setTimeout(() => {
					compile(config.root, true).then(
						() => server.ws.send({ type: 'full-reload' }),
						(e: Error) => server.config.logger.error(e.message)
					);
				}, 50);
			});
		}
	};
}
