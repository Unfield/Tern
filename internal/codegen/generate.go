func writeIfChanged(name string, data []byte) (bool, error) {
	if old, err := os.ReadFile(name); err == nil && bytes.Equal(old, data) {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(name), 0o755); err != nil {
		return false, err
	}
	tmp := name + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return false, err
	}
	return true, os.Rename(tmp, name)
}

// removeStaleTypes deletes $types.d.ts files for routes that no longer exist.
func (g *generator) removeStaleTypes() error {
	dir := filepath.Join(g.root, GenDir, "types")
	return filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(g.root, p)
		if err != nil {
			return err
		}
		if _, ok := g.files[filepath.ToSlash(rel)]; !ok {
			return os.Remove(p)
		}
		return nil
	})
}

func intSlice(v []int) string {
	parts := make([]string, len(v))
	for i, n := range v {
		parts[i] = strconv.Itoa(n)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func goInts(v []int) string {
	return "[]int{" + strings.Trim(intSlice(v), "[]") + "}"
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
