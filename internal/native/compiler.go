// Problem is something the compiler couldn't compile. The code compiles
// to a stub that raises js.Unsupported when it runs, so only a request that
// reaches it falls back to the JavaScript engine.
type Problem struct {
	Module string
	Offset int
	What   string
}

func (p Problem) String() string { return fmt.Sprintf("%s:%d: %s", p.Module, p.Offset, p.What) }

// Result is a compiled app.
type Result struct {
	// Source is the Go file, package native.
	Source []byte
	// Problems lists what couldn't be compiled, in module order.
	Problems []Problem
	// Modules is how many modules were compiled.
	Modules int
	// Mismatches lists the intrinsics not used because the function they
	// stand for has changed, with its fingerprint now.
	Mismatches []string
	// Sources is the modules' code, gzipped, for Options.EmbedSources.
	Sources []byte
}

// nativeModules are the imports Go provides, by specifier.
var nativeModules = map[string]string{
	"svelte/internal/server": "js.NewNamespace()",
	"svelte/server":          "js.NewNamespace()",
	"svelte":                 "js.NewNamespace()",
	"esm-env":                "js.NewNamespace()",
}

type module struct {
	id      string
	index   int
	ast     *Node
	imports map[string]*string
	goType  string // m3
	goVar   string // M3
	scope   *scope
	// exports maps export names to the Go expression of their binding.
	exports map[string]string
	// starFrom lists modules whose exports `export * from` re-exports.
	starFrom []*module
	// zero is the module struct's initial value: every binding undefined.
	zero string
	// deps are the modules it imports, in order; dynamic those it import()s.
	deps, dynamic []*module
	resolved      bool
}

// Compiler turns the IR into Go.
type Compiler struct {
	opts       Options
	mismatches []string
	globalRefs int
	fnInfos    []string
	ics        int
	ir         *IR
	mods       map[string]*module
	order      []*module
	problems   []Problem
	tmp        int
	cur        *module
}

// Options say how the Go comes out.
type Options struct {
	// Package is the Go package name; the default is native.
	Package string
	// Prefix starts the names the file declares, so it can share a package:
	// with "tern", the realm type is ternRealm and New is ternNew.
	Prefix string
	// Register, if set, is an assignable expression, such as
	// "ternManifest.Native", that an init function sets to New.
	Register string
	// EmbedSources, if set, is the path the caller writes Result.Sources
	// to, which the file embeds; otherwise the sources are in the file.
	EmbedSources string
}

// Compile compiles the IR's modules reachable from its entry.
func Compile(ir *IR, opts Options) (*Result, error) {
	if opts.Package == "" {
		opts.Package = "native"
	}
	c := &Compiler{ir: ir, mods: map[string]*module{}, opts: opts}
	for i, m := range ir.Modules {
		c.mods[m.ID] = &module{id: m.ID, index: i, ast: m.AST, imports: m.Imports, goType: c.name("m" + strconv.Itoa(i)), goVar: "r.M" + strconv.Itoa(i)}
	}
	entry, ok := c.mods[ir.Entry]
	if !ok {
		return nil, fmt.Errorf("native: the entry %s is not in the IR", ir.Entry)
	}
	seen := map[*module]bool{}
	c.visit(entry, seen)
	// Modules only imported dynamically come after, loaded when imported.
	for i := 0; i < len(c.order); i++ {
		for _, dep := range c.order[i].dynamic {
			c.visit(dep, seen)
		}
	}
	for _, m := range c.order {
		c.declareModule(m)
	}
	for _, m := range c.order {
		c.resolveExports(m, map[*module]bool{})
	}
	var b strings.Builder
	b.WriteString("// Code generated by tern build from the server build's modules. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\nimport (", opts.Package)
	if opts.EmbedSources != "" {
		b.WriteString("\n\t\"embed\"\n")
	}
	b.WriteString("\n\t\"github.com/Unfield/Tern/native/js\"\n\t\"github.com/Unfield/Tern/native/svelte\"\n)\n\n")
	b.WriteString("var _ = svelte.Escape\n\n")
	if opts.EmbedSources != "" {
		b.WriteString("var _ embed.FS\n\n")
	}
	var mods strings.Builder
	for _, m := range c.order {
		c.cur = m
		mods.WriteString(c.compileModule(m))
	}
	// The realm holds everything that changes: the modules' variables and
	// the caches. Each realm runs on its own.
	realmType, newFunc := c.name("realm"), c.name("New")
	if opts.Prefix == "" {
		newFunc = "New"
	}
	fmt.Fprintf(&b, "// %s is a js.Realm with the app's modules in it.\ntype %s struct {\n\t*js.Realm\n", realmType, realmType)
	for _, m := range c.order {
		fmt.Fprintf(&b, "\t%s %s\n", strings.TrimPrefix(m.goVar, "r."), m.goType)
	}
	fmt.Fprintf(&b, "\tics     [%d]js.IC\n\tglobals [%d]js.GlobalRef\n\tloaded  [%d]bool\n}\n\n", c.ics, c.globalRefs, len(ir.Modules))
	fmt.Fprintf(&b, "// %s makes a realm and evaluates the app's modules in it, in the order\n// JavaScript would. setup, if not nil, runs first: it adds host functions.\nfunc %s(setup func(*js.Realm)) *js.Realm {\n\tr := &%s{Realm: js.NewRealm()}\n\tif setup != nil {\n\t\tsetup(r.Realm)\n\t}\n", newFunc, newFunc, realmType)
	for _, m := range c.order {
		fmt.Fprintf(&b, "\t%s\n", m.zero)
	}
	fmt.Fprintf(&b, "\tr.load%d()\n", entry.index)
	b.WriteString("\treturn r.Realm\n}\n\n")
	// Each module loads its imports, then runs, once: the order ES modules
	// evaluate in, and how import() loads what nothing else did.
	for _, m := range c.order {
		fmt.Fprintf(&mods, "func (r *realm) load%d() {\n\tif r.loaded[%d] {\n\t\treturn\n\t}\n\tr.loaded[%d] = true\n", m.index, m.index, m.index)
		for _, d := range m.deps {
			fmt.Fprintf(&mods, "\tr.load%d()\n", d.index)
		}
		fmt.Fprintf(&mods, "\tr.init%d()\n}\n\n", m.index)
	}
	if opts.Register != "" {
		fmt.Fprintf(&b, "func init() { %s = %s }\n\n", opts.Register, newFunc)
	}
	b.WriteString(strings.ReplaceAll(realmCalls(mods.String()), "(r *realm)", "(r *"+realmType+")"))

	// The functions' names, lengths and where their source text is.
	sources := c.sources()
	srcVar := c.name("sourcesGz")
	if opts.EmbedSources != "" {
		fmt.Fprintf(&b, "\n//go:embed %s\nvar %s string\n", opts.EmbedSources, srcVar)
	} else {
		fmt.Fprintf(&b, "\nvar %s = %q\n", srcVar, sources)
	}
	fmt.Fprintf(&b, "\nvar %s = js.Sources{GZ: &%s}\n\n", c.name("sources"), srcVar)
	for _, d := range c.fnInfos {
		b.WriteString(d)
	}
	src := []byte(b.String())
	formatted, err := format.Source(src)
	if err != nil {
		return &Result{Source: src, Problems: c.problems, Modules: len(c.order)}, fmt.Errorf("native: generated Go doesn't parse: %w", err)
	}
	sort.SliceStable(c.problems, func(i, j int) bool { return c.mods[c.problems[i].Module].index < c.mods[c.problems[j].Module].index })
	return &Result{Source: formatted, Problems: c.problems, Modules: len(c.order), Mismatches: c.mismatches, Sources: sources}, nil
}

// visit orders modules as ESM evaluates them: each module after its imports.
func (c *Compiler) visit(m *module, seen map[*module]bool) {
	if seen[m] {
		return
	}
	seen[m] = true
	for _, n := range m.ast.List("body") {
		switch n.Type {
		case "ImportDeclaration", "ExportAllDeclaration", "ExportNamedDeclaration":
			src := n.Child("source")
			if src == nil {
				continue
			}
			if dep := c.resolveModule(m, src.Str("value")); dep != nil {
				m.deps = append(m.deps, dep)
				c.visit(dep, seen)
			}
		}
	}
	walkNodes(m.ast, func(n *Node) {
		if n.Type == "ImportExpression" {
			if src := n.Child("source"); src != nil && src.Type == "Literal" {
				if dep := c.resolveModule(m, src.Str("value")); dep != nil {
					m.dynamic = append(m.dynamic, dep)
				}
			}
		}
	})
	c.order = append(c.order, m)
}

// resolveModule is the recorded module an import resolves to, or nil for native
// modules and ones the IR doesn't have.
func (c *Compiler) resolveModule(m *module, spec string) *module {
	id, ok := m.imports[spec]
	if !ok || id == nil {
		return nil
	}
	if !c.kept(*id) {
		return nil // tree-shaken: see isShaken
	}
	return c.mods[*id]
}

// kept reports whether a module is compiled: the bundle has it, or it is
// a barrel, only imports and exports, which the bundler removes while
// keeping what it re-exports.
func (c *Compiler) kept(id string) bool {
	if c.ir.Bundled == nil || c.ir.Bundled[id] {
		return true
	}
	m := c.mods[id]
	if m == nil {
		return false
	}
	for _, n := range m.ast.List("body") {
		switch n.Type {
		case "ImportDeclaration", "ExportAllDeclaration":
		case "ExportNamedDeclaration":
			if n.Child("declaration") != nil {
				return false
			}
		default:
			return false
		}
	}
	return true
}

// isShaken reports whether an import is of a module the bundler left out:
// nothing the bundle runs uses it, so it isn't compiled.
func (c *Compiler) isShaken(m *module, spec string) bool {
	id, ok := m.imports[spec]
	return ok && id != nil && c.mods[*id] != nil && !c.kept(*id)
}

func (c *Compiler) problem(n *Node, format string, args ...any) {
	off := 0
	if n != nil {
		off = n.Start
	}
	c.problems = append(c.problems, Problem{Module: c.cur.id, Offset: off, What: fmt.Sprintf(format, args...)})
}

func (c *Compiler) temp(prefix string) string {
	c.tmp++
	return prefix + strconv.Itoa(c.tmp)
}

// goIdent makes a JavaScript identifier into a Go one: v_ plus the name,
// with $ as _S.
func goIdent(name string) string {
	var b strings.Builder
	b.WriteString("v_")
	for _, r := range name {
		switch {
		case r == '$':
			b.WriteString("_S")
		case r == '_' || r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z':
			b.WriteRune(r)
		default:
			fmt.Fprintf(&b, "_u%x_", r)
		}
	}
	return b.String()
}

// quote is a Go string literal holding the exact bytes of s, including
// WTF-8 surrogates.
func quote(s string) string { return strconv.Quote(s) }

// fnInfo declares a function's js.FnInfo and returns its name.
func (c *Compiler) fnInfo(name string, length int, n *Node) string {
	v := c.name("fi" + strconv.Itoa(len(c.fnInfos)))
	src := "nil"
	if c.ir.Modules[c.cur.index].Code != "" {
		src = "&" + c.name("sources")
	}
	c.fnInfos = append(c.fnInfos, fmt.Sprintf("var %s = js.FnInfo{Name: %s, Length: %d, Src: %s, Module: %d, Start: %d, End: %d}\n", v, quote(name), length, src, c.cur.index, n.Start, n.End))
	return v
}

// sources gzips the modules' code as a JSON array, in IR order.
func (c *Compiler) sources() []byte {
	codes := make([]string, len(c.ir.Modules))
	for _, m := range c.order {
		codes[m.index] = c.ir.Modules[m.index].Code
	}
	raw, _ := json.Marshal(codes)
	var buf bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	_, _ = zw.Write(raw)
	_ = zw.Close()
	return buf.Bytes()
}

// name prefixes a name the generated file declares.
func (c *Compiler) name(s string) string {
	if c.opts.Prefix == "" {
		return s
	}
	return c.opts.Prefix + strings.ToUpper(s[:1]) + s[1:]
}

// realmNames are the names of js.Realm's exported methods and fields:
// compiled code reaches them through its realm, r.
var realmNames = func() map[string]bool {
	out := map[string]bool{}
	t := reflect.TypeOf(&js.Realm{})
	for i := range t.NumMethod() {
		out[t.Method(i).Name] = true
	}
	for i := range t.Elem().NumField() {
		if f := t.Elem().Field(i); f.IsExported() {
			out[f.Name] = true
		}
	}
	return out
}()

var jsName = regexp.MustCompile(`\bjs\.([A-Z][A-Za-z0-9]*)`)

// realmCalls rewrites js.Name to r.Name where Name belongs to the realm,
// and points the caches at the realm's.
func realmCalls(src string) string {
	src = jsName.ReplaceAllStringFunc(src, func(m string) string {
		if realmNames[m[3:]] {
			return "r." + m[3:]
		}
		return m
	})
	src = strings.ReplaceAll(src, "&ics[", "&r.ics[")
	return strings.ReplaceAll(src, "&globals[", "&r.globals[")
}
