package main

import (
	"context"
	"log"
	"os"

	"github.com/Unfield/Tern/kit"
	"github.com/Unfield/Tern/migrate"

	"shelf/internal/shelf"
	"shelf/migrations"
)

func main() {
	path := os.Getenv("DATABASE")
	if path == "" {
		path = "shelf.db"
	}
	app, err := newApp(path)
	if err != nil {
		log.Fatal(err)
	}
	if err := app.ListenAndServe(); err != nil {
		log.Fatal(err)
	}
}

// newApp opens the database at path and returns the app. The tests call
// it too, each with a database of its own.
func newApp(path string) (*kit.App, error) {
	if err := shelf.Open(context.Background(), path); err != nil {
		return nil, err
	}
	provider, server, err := assistants()
	if err != nil {
		return nil, err
	}
	panel, err := adminPanel()
	if err != nil {
		return nil, err
	}
	// ternApp is generated by tern in tern.gen.go, from src/routes.
	return ternApp(kit.WithPlugins(
		migrate.Plugin(shelf.DB, migrations.FS),
		shelf.Accounts,
		provider,
		server,
		panel,
	))
}
